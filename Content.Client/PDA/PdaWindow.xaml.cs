using System.Numerics;
using Content.Client.DeadSpace.Stylesheets; // DS14
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.PDA;

[Virtual]
[GenerateTypedNameReferences]
public partial class PdaWindow : BaseWindow
{

    public string? BorderColor
    {
        get => Background.ActualModulateSelf.ToHex();

        // DS14-start
        set
        {
            _borderColor = value;
            UpdateHologramChrome();
        }
        // DS14-end
    }

    public string? AccentHColor
    {
        get => AccentH.ActualModulateSelf.ToHex();

        set
        {
            AccentH.ModulateSelfOverride = Color.FromHex(value, Color.White);
            AccentH.Visible = value != null;
            // DS14-start
            _accentHColor = value;
            UpdateHologramChrome();
            // DS14-end
        }
    }

    public string? AccentVColor
    {
        get => AccentV.ActualModulateSelf.ToHex();

        set
        {
            AccentV.ModulateSelfOverride = Color.FromHex(value, Color.White);
            AccentV.Visible = value != null;
            // DS14-start
            _accentVColor = value;
            UpdateHologramChrome();
            // DS14-end
        }
    }

    private const int DRAG_MARGIN_SIZE = 7; // DS14

    // DS14-start
    /// <summary>Content margins of the "Dead Space" style: the projected window has no coloured case around the screen.</summary>
    private static readonly Thickness HologramContentMargin = new(10, 6, 10, 0);

    private string? _borderColor;
    private string? _accentHColor;
    private string? _accentVColor;
    private readonly Thickness _contentMargin;
    private bool? _hologram;
    // DS14-end

    public PdaWindow()
    {
        RobustXamlLoader.Load(this);

        CloseButton.OnPressed += _ => Close();
        XamlChildren = ContentsContainer.Children;

        AccentH.Visible = false;
        AccentV.Visible = false;

        _contentMargin = ContentFrame.Margin; // DS14
    }

    // DS14-start
    /// <summary>
    /// Title in the window header of the "Dead Space" style; other styles have no header title.
    /// </summary>
    public void SetHologramTitle(string title, string? subtitle)
    {
        HoloTitleLabel.Text = title;
        HoloSubtitleLabel.Text = subtitle;
        HoloSubtitleLabel.Visible = !string.IsNullOrEmpty(subtitle);
    }

    /// <summary>
    /// Called when the window switches into or out of the "Dead Space" style, and once on the first styling.
    /// </summary>
    protected virtual void HologramChanged(bool hologram)
    {
    }

    protected override void StylePropertiesChanged()
    {
        base.StylePropertiesChanged();
        UpdateHologramChrome();

        var hologram = DeadSpaceStylePalette.Hologram;
        if (_hologram == hologram)
            return;

        _hologram = hologram;
        HologramChanged(hologram);
    }

    /// <summary>
    /// The "Dead Space" style projects the PDA like any other window: the palette frame and brackets replace the
    /// case and accent stripes in the PDA's own colour. Other styles keep them.
    /// </summary>
    private void UpdateHologramChrome()
    {
        var hologram = DeadSpaceStylePalette.Hologram;

        Background.ModulateSelfOverride = hologram || _borderColor == null
            ? null
            : Color.FromHex(_borderColor, Color.White);
        AccentH.Visible = !hologram && _accentHColor != null;
        AccentV.Visible = !hologram && _accentVColor != null;

        HoloTitleBox.Visible = hologram;

        ContentFrame.Margin = hologram ? HologramContentMargin : _contentMargin;
    }
    // DS14-end

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        // DS14-start
        var mode = DragMode.Move;

        if (Resizable)
        {
            if (relativeMousePos.Y < DRAG_MARGIN_SIZE)
                mode = DragMode.Top;
            else if (relativeMousePos.Y > Size.Y - DRAG_MARGIN_SIZE)
                mode = DragMode.Bottom;

            if (relativeMousePos.X < DRAG_MARGIN_SIZE)
                mode |= DragMode.Left;
            else if (relativeMousePos.X > Size.X - DRAG_MARGIN_SIZE)
                mode |= DragMode.Right;
        }

        return mode;
        // DS14-end
    }
}
