using Content.Client.DeadSpace.UserInterface.Hologram.Options; // DS14
using Content.Client.Info;
using Content.Client.UserInterface.Systems.EscapeMenu;
using Content.Client.UserInterface.Systems.Guidebook;
using Robust.Client.AutoGenerated;
using Robust.Client.Console;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing; // DS14

namespace Content.Client.Lobby.UI
{
    [GenerateTypedNameReferences]
    public sealed partial class LobbyGui : UIScreen
    {
        [Dependency] private IClientConsoleHost _consoleHost = default!;
        [Dependency] private IUriOpener _uriOpener = default!;

        private readonly HologramCaps _caps = new(); // DS14

        public LobbyGui()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this);
            SetAnchorPreset(MainContainer, LayoutPreset.Wide);
            SetAnchorPreset(Background, LayoutPreset.Wide);
            SetAnchorPreset(ParallaxControl, LayoutPreset.Wide);

            LeaveButton.OnPressed += _ => _consoleHost.ExecuteCommand("disconnect");
            OptionsButton.OnPressed += _ => UserInterfaceManager.GetUIController<OptionsUIController>().ToggleWindow();

            Wiki.OnPressed += _ => _uriOpener.OpenUri(new Uri("https://wiki.deadspace14.net"));
            Boosty.OnPressed += _ => _uriOpener.OpenUri(new Uri("https://boosty.to/deadstation14"));
            Discord.OnPressed += _ => _uriOpener.OpenUri(new Uri("https://discord.gg/ds14"));
            Telegram.OnPressed += _ => _uriOpener.OpenUri(new Uri("https://t.me/mk_ss14"));
            Site.OnPressed += _ => _uriOpener.OpenUri(new Uri("https://deadspace14.net"));

            Rules.OnPressed += _ => new RulesAndInfoWindow().Open();
            Guidebook.OnPressed += _ => UserInterfaceManager.GetUIController<GuidebookUIController>().ToggleGuidebook();
            Changelog.OnPressed += _ => UserInterfaceManager.GetUIController<ChangelogUIController>().ToggleWindow();

            ShowGUI.OnPressed += _ => ChangeVisibility(); // DS14

            // DS14-start: uppercase captions of the panels and the lobby actions in the "Dead Space" style
            _caps.Add(ServerInfoTitle);
            _caps.Add(RoundStartTitle);
            _caps.AddButtons(CenterPanel);
            _caps.Add(CallVoteButton);
            InitializeHologram();
            // DS14-end
        }

        // DS14-start
        protected override void FrameUpdate(FrameEventArgs args)
        {
            base.FrameUpdate(args);
            UpdateHologram();
            _caps.Update();
        }
        // DS14-end

        public void SwitchState(LobbyGuiState state)
        {
            switch (state)
            {
                case LobbyGuiState.Default:
                    CharacterSetupState.Visible = false;
                    SplitContainer.Visible = true;
                    break;
                case LobbyGuiState.CharacterSetup:
                    CharacterSetupState.Visible = true;
                    SplitContainer.Visible = false;
                    UserInterfaceManager.GetUIController<LobbyUIController>().ReloadCharacterSetup();
                    break;
            }

            UpdateHologramVisibility(); // DS14: the Dead Space lobby replaces the split layout
        }
        // DS14-start
        private void ChangeVisibility()
        {
            ShowGUI.Pressed = !ShowGUI.Pressed;
            CenterPanel.Visible = !ShowGUI.Pressed;
            BottomContainer.Visible = !ShowGUI.Pressed;
            UpdateHologramVisibility();
        }
        // DS14-end

        public enum LobbyGuiState : byte
        {
            /// <summary>
            ///  The default state, i.e., what's seen on launch.
            /// </summary>
            Default,
            /// <summary>
            ///  The character setup state.
            /// </summary>
            CharacterSetup
        }
    }
}
