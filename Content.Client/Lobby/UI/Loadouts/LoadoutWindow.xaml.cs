[GenerateTypedNameReferences]
public sealed partial class LoadoutWindow : FancyWindow
{
    public event Action<string>? OnNameChanged;
    public event Action<ProtoId<LoadoutGroupPrototype>, ProtoId<LoadoutPrototype>>? OnLoadoutPressed;
    public event Action<ProtoId<LoadoutGroupPrototype>, ProtoId<LoadoutPrototype>>? OnLoadoutUnpressed;
    public event Action<ProtoId<SiliconLawsetPrototype>>? OnAiLawsetChanged; // DS14

    private List<LoadoutGroupContainer> _groups = new();

    public HumanoidCharacterProfile Profile;

    // CCvar.
    private int _maxLoadoutNameLength;

    private static readonly ProtoId<RoleLoadoutPrototype> StationAiRole = LoadoutSystem.GetJobPrototype("StationAi"); // DS14

    public LoadoutWindow(HumanoidCharacterProfile profile, RoleLoadout loadout, RoleLoadoutPrototype proto, ICommonSession session, IDependencyCollection collection)
    {
        RobustXamlLoader.Load(this);
        Profile = profile;
        var protoManager = collection.Resolve<IPrototypeManager>();
        var configManager = collection.Resolve<IConfigurationManager>();

        _maxLoadoutNameLength = configManager.GetCVar(CCVars.MaxLoadoutNameLength);
        RoleNameEdit.IsValid = text => text.Length <= _maxLoadoutNameLength;

        // Hide if we can't edit the name.
        if (!proto.CanCustomizeName)
        {
            RoleNameBox.Visible = false;
        }
        else
        {
            var name = loadout.EntityName;

            LoadoutNameLabel.Text = proto.NameDataset == null ?
                Loc.GetString("loadout-name-edit-label") :
                Loc.GetString("loadout-name-edit-label-dataset");

            RoleNameEdit.ToolTip = Loc.GetString(
                "loadout-name-edit-tooltip",
                ("max", _maxLoadoutNameLength));
            RoleNameEdit.Text = name ?? string.Empty;
            RoleNameEdit.OnTextChanged += args => OnNameChanged?.Invoke(args.Text);
        }

        // Hide if no groups
        var isStationAi = loadout.Role == StationAiRole || proto.NameDataset?.Id == "NamesAI"; // DS14
        if (proto.Groups.Count == 0 && !isStationAi) // DS14
        {
            LoadoutGroupsContainer.Visible = false;
            SetSize = Vector2.Zero;
        }
        else
        {
            foreach (var group in proto.Groups)
            {
                if (!protoManager.Resolve(group, out var groupProto))
                    continue;

                if (groupProto.Hidden)
                    continue;

                var container = new LoadoutGroupContainer(profile, loadout, protoManager.Index(group), session, collection);
                LoadoutGroupsContainer.AddTab(container, Loc.GetString(groupProto.Name));
                _groups.Add(container);

                container.OnLoadoutPressed += args =>
                {
                    OnLoadoutPressed?.Invoke(group, args);
                };

                container.OnLoadoutUnpressed += args =>
                {
                    OnLoadoutUnpressed?.Invoke(group, args);
                };
            }

            // DS14-start
            if (isStationAi)
            {
                AddStationAiTab(profile, protoManager);

                if (proto.Groups.Count == 0)
                    SetSize = new Vector2(800, 220);
            }
            // DS14-end
        }
    }

    // DS14-start
    private void AddStationAiTab(HumanoidCharacterProfile profile, IPrototypeManager protoManager)
    {
        var container = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(10),
        };

        container.AddChild(new Label
        {
            Text = Loc.GetString("loadout-ai-lawset-description"),
            HorizontalExpand = true,
        });

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(0, 8, 0, 0),
        };

        row.AddChild(new Label
        {
            Text = Loc.GetString("loadout-ai-lawset-label"),
            VerticalAlignment = VAlignment.Center,
        });

        row.AddChild(new Control { HorizontalExpand = true });

        var button = new OptionButton { HorizontalAlignment = HAlignment.Right };

        var selected = 0;
        for (var i = 0; i < StationAiLawsets.Available.Length; i++)
        {
            var id = StationAiLawsets.Available[i];
            if (!protoManager.TryIndex(id, out var lawset))
                continue;

            var name = lawset.Name is { } lawsetName ? Loc.GetString(lawsetName) : id.Id;
            button.AddItem(name, i);

            if (profile.StationAiLawset == id)
                selected = i;
        }

        if (StationAiLawsets.Available.Length > 0)
            button.TrySelectId(selected);

        button.OnItemSelected += args =>
        {
            button.SelectId(args.Id);
            OnAiLawsetChanged?.Invoke(StationAiLawsets.Available[args.Id]);
        };

        row.AddChild(button);
        container.AddChild(row);
        LoadoutGroupsContainer.AddTab(container, Loc.GetString("loadout-ai-laws-tab"));
    }
    // DS14-end

    public void RefreshLoadouts(RoleLoadout loadout, ICommonSession session, IDependencyCollection collection)
    {
        foreach (var group in _groups)
        {
            group.RefreshLoadouts(Profile, loadout, session, collection);
        }
    }
}
