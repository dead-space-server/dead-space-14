using Content.Client.DeadSpace.Stylesheets; // DS14
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Communications.UI.Widgets;

/// <summary>
/// A set of controls to change the alert level for a station.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class AlertLevelControls : BoxContainer
{
    // DS14-start - the current engine still uses the pre-source-generator IoC pattern.
    [Dependency] private ILocalizationManager _loc = default!;
    // DS14-end

    private bool _alertLevelSelectable;
    private string? _currentAlertLevel;
    private Color _currentAlertColor = Color.White; // DS14

    public event Action<string>? OnAlertLevelChanged;

    public AlertLevelControls()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        AlertLevelSelector.OnItemSelected += args =>
        {
            AlertLevelSelector.Select(args.Id);
            EnableDisableConfirmLevelChangeButton();
            HologramLevels.SyncSelection(AlertLevelSelector.GetIdx(AlertLevelSelector.SelectedId)); // DS14
        };

        // DS14-start
        HologramLevels.LevelPressed += idx =>
        {
            AlertLevelSelector.Select(idx);
            EnableDisableConfirmLevelChangeButton();
            HologramLevels.SyncSelection(idx);
        };
        // DS14-end

        ConfirmAlertLevelButton.OnPressed += _ =>
        {
            var metadata = AlertLevelSelector.GetItemMetadata(AlertLevelSelector.SelectedId);
            if (metadata is string selected)
                OnAlertLevelChanged?.Invoke(selected);
        };

        AlertLevelSelector.Disabled = !_alertLevelSelectable;
    }

    /// <summary>
    /// Updates the UI components to display the current alert level and the
    /// selectable alert levels.
    /// </summary>
    // DS14-start - use server-provided alert IDs and color until alert levels move to Shared.
    public void UpdateAlertLevels(List<string>? selectableAlertLevels,
        string currentAlertLevel,
        Color currentAlertColor,
        bool alertLevelSelectable)
    {
        _alertLevelSelectable = alertLevelSelectable;
        _currentAlertLevel = currentAlertLevel;
        _currentAlertColor = currentAlertColor; // DS14
        CurrentAlertLevelLabel.Text = GetLocalizedAlertName(currentAlertLevel);
        CurrentAlertLevelLabel.ModulateSelfOverride = currentAlertColor;

        AlertLevelSelector.Disabled = selectableAlertLevels == null || !_alertLevelSelectable;

        // If user had changed the selection, but hadn't pressed the confirm
        // button at the point we received an update message, remember it so it
        // can be re-selected if it is still available.
        string? previousSelection = null;
        if (AlertLevelSelector.ItemCount > 1)
        {
            var metadata = AlertLevelSelector.GetItemMetadata(AlertLevelSelector.SelectedId);
            if (metadata is string selected)
                previousSelection = selected;
        }

        AlertLevelSelector.Clear();
        AlertLevelSelector.AddItem(Loc.GetString("comms-console-change-alert-level-button"));
        AlertLevelSelector.Select(0);

        if (selectableAlertLevels != null)
        {
            foreach (var alert in selectableAlertLevels)
            {
                AlertLevelSelector.AddItem(GetLocalizedAlertName(alert));
                AlertLevelSelector.SetItemMetadata(AlertLevelSelector.ItemCount - 1, alert);

                if (alert == previousSelection)
                    AlertLevelSelector.Select(AlertLevelSelector.ItemCount - 1);
            }
        }

        if (_loc.TryGetString($"comms-console-level-{currentAlertLevel}-flavour-label", out var flavour))
            CurrentAlertLevelFlavorLabel.Text = flavour;
        else
            CurrentAlertLevelFlavorLabel.Text = string.Empty;

        EnableDisableConfirmLevelChangeButton();
        UpdateHologramLevels(); // DS14
    }
    // DS14-end

    // DS14-start
    protected override void StylePropertiesChanged()
    {
        base.StylePropertiesChanged();

        // The button row replaces the dropdown in the Dead Space style; the confirm button stays and moves right.
        var hologram = DeadSpaceStylePalette.Hologram;
        HologramLevels.Visible = hologram;
        AlertLevelSelector.Visible = !hologram;
        ConfirmAlertLevelButton.HorizontalExpand = !hologram;
        ConfirmAlertLevelButton.HorizontalAlignment = hologram ? HAlignment.Right : HAlignment.Stretch;
    }

    private void UpdateHologramLevels()
    {
        var levels = new List<(int Index, string Level, string Name)>();
        for (var idx = 1; idx < AlertLevelSelector.ItemCount; idx++)
        {
            if (AlertLevelSelector.GetItemMetadata(idx) is string level)
                levels.Add((idx, level, GetLocalizedAlertName(level)));
        }

        HologramLevels.Update(levels,
            _currentAlertLevel,
            _currentAlertColor,
            !AlertLevelSelector.Disabled,
            AlertLevelSelector.GetIdx(AlertLevelSelector.SelectedId));
    }
    // DS14-end

    /// <summary>
    /// Configure the confirm button to be consistent with the server state and user interactions.
    /// </summary>
    private void EnableDisableConfirmLevelChangeButton()
    {
        var selectedId = AlertLevelSelector.SelectedId;
        ConfirmAlertLevelButton.Disabled = !_alertLevelSelectable || selectedId == 0;
        if (selectedId == 0)
            return;

        var metadata = AlertLevelSelector.GetItemMetadata(selectedId);
        if (metadata is string selected)
            ConfirmAlertLevelButton.Disabled |= selected == _currentAlertLevel;
    }

    private string GetLocalizedAlertName(string alertLevel)
    {
        return _loc.TryGetString($"alert-level-{alertLevel}", out var localized)
            ? localized
            : alertLevel;
    }
}
