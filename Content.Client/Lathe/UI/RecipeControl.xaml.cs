using System.Numerics; // DS14
using Content.Client.DeadSpace.Stylesheets; // DS14
using Content.Shared.Research.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls; // DS14
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.Lathe.UI;

[GenerateTypedNameReferences]
public sealed partial class RecipeControl : Control
{
    public Action<string>? OnButtonPressed;
    public Func<string> TooltipTextSupplier;

    private ProtoId<LatheRecipePrototype> _recipeId;
    private LatheSystem _latheSystem;

    public RecipeControl(LatheSystem latheSystem, LatheRecipePrototype recipe, Func<string> tooltipTextSupplier, bool canProduce, Control displayControl)
    {
        RobustXamlLoader.Load(this);

        _latheSystem = latheSystem;
        _recipeId = recipe.ID;
        TooltipTextSupplier = tooltipTextSupplier;
        SetRecipe(recipe);
        SetCanProduce(canProduce);
        SetDisplayControl(displayControl);

        Button.OnPressed += (_) =>
        {
            OnButtonPressed?.Invoke(_recipeId);
        };
        Button.TooltipSupplier = SupplyTooltip;
    }

    public void SetRecipe(LatheRecipePrototype recipe)
    {
        RecipeName.Text = _latheSystem.GetRecipeName(recipe);
        _recipeId = recipe.ID;
    }

    public void SetTooltipSupplier(Func<string> tooltipTextSupplier)
    {
        TooltipTextSupplier = tooltipTextSupplier;
    }

    public void SetCanProduce(bool canProduce)
    {
        Button.Disabled = !canProduce;
    }

    public void SetDisplayControl(Control displayControl)
    {
        RecipeDisplayContainer.Children.Clear();
        RecipeDisplayContainer.AddChild(displayControl);

        // DS14-start: icons at 2x in the Dead Space style.
        if (!DeadSpaceStylePalette.Hologram)
            return;

        displayControl.SetSize = new Vector2(64, 64);
        if (displayControl is TextureRect texture)
            texture.Stretch = TextureRect.StretchMode.KeepAspectCentered;
        else if (displayControl is SpriteView sprite)
            sprite.Stretch = SpriteView.StretchMode.Fill;
        // DS14-end
    }

    // DS14-start
    /// <summary>Shows the materials of the recipe and an add marker; null hides both.</summary>
    public void SetCost(string? cost)
    {
        CostLabel.Visible = cost != null;
        AddBadge.Visible = cost != null;
        if (cost == null)
            return;

        CostLabel.Text = cost;
        CostLabel.FontColorOverride = DeadSpaceStylePalette.TextMuted;
        AddLabel.FontColorOverride = DeadSpaceStylePalette.CyanBright;
        AddBadge.PanelOverride = DeadSpaceStyleBoxes.Holo(Color.Transparent, DeadSpaceStylePalette.BorderControl);
    }
    // DS14-end

    private Control? SupplyTooltip(Control sender)
    {
        return new RecipeTooltip(TooltipTextSupplier());
    }
}
