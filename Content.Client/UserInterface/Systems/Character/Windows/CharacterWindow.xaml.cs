using Content.Client.DeadSpace.Stylesheets; // DS14
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.UserInterface.Systems.Character.Windows;

[GenerateTypedNameReferences]
public sealed partial class CharacterWindow : DefaultWindow
{
    public CharacterWindow()
    {
        RobustXamlLoader.Load(this);
        // DS14-start
        MemoryLabel.Text = Loc.GetString("hologram-character-memory").ToUpperInvariant();
        ApplyChrome();
        // DS14-end
    }

    // DS14-start
    protected override void StylePropertiesChanged()
    {
        base.StylePropertiesChanged();
        ApplyChrome();
    }

    /// <summary>Square portrait frame in the active palette; re-run on restyle so a style change applies at once.</summary>
    private void ApplyChrome()
    {
        PortraitFrame.PanelOverride = DeadSpaceStyleBoxes.Flat(
            DeadSpaceStylePalette.SurfaceInset,
            DeadSpaceStylePalette.Hologram ? DeadSpaceStylePalette.BorderControl : DeadSpaceStylePalette.BorderDark,
            new Thickness(1));
    }
    // DS14-end
}
