using System.Linq;
using System.Numerics;
using Content.Client.DeadSpace.Stylesheets;
using Content.Shared.DeadSpace.OrganPrinter;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client.DeadSpace.OrganPrinter;

[GenerateTypedNameReferences]
public sealed partial class OrganPrinterWindow : DefaultWindow
{
    [Dependency] private IPrototypeManager _proto = default!;

    public event Action<EntProtoId, OrganSpeciesGroup>? OnPrint;
    public event Action? OnEjectPressed;

    private List<OrganPrinterProduct> _products = new();
    private List<OrganPrinterProduct> _filtered = new();
    private OrganSpeciesGroup? _groupFilter = OrganSpeciesGroup.Humanoid;
    private OrganPrinterProduct? _selected;
    private int _biomass;
    private bool _printing;

    public OrganPrinterWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        PrintButton.OnPressed += _ =>
        {
            if (_selected is { } selected)
                OnPrint?.Invoke(selected.Product, selected.Group);
        };

        var groups = Enum.GetValues<OrganSpeciesGroup>().ToList();
        foreach (var group in groups)
            GroupFilter.AddItem(Loc.GetString($"organ-printer-group-{group.ToString().ToLowerInvariant()}"));
        GroupFilter.SelectId(0);
        GroupFilter.OnItemSelected += args =>
        {
            GroupFilter.SelectId(args.Id);
            _groupFilter = groups[args.Id];
            RebuildList();
        };

        EjectButton.OnPressed += _ => OnEjectPressed?.Invoke();
    }

    public void UpdateState(OrganPrinterUpdateState state)
    {
        _biomass = state.Biomass;
        _printing = state.Printing;

        var changed = !_products.Select(p => (p.Product, p.Cost, p.Group))
            .SequenceEqual(state.Products.Select(p => (p.Product, p.Cost, p.Group)));
        _products = state.Products;

        if (changed)
        {
            if (_selected is { } selected && _products.All(p => p.Product != selected.Product || p.Group != selected.Group))
                _selected = null;
            RebuildList();
        }

        UpdateSelection();
        UpdateBottomPanel();
    }

    private void RebuildList()
    {
        _filtered = _products
            .Where(p => _groupFilter == null || p.Group == _groupFilter)
            .ToList();

        OrganList.RemoveAllChildren();

        if (_filtered.Count == 0)
        {
            OrganList.AddChild(new Label
            {
                Text = Loc.GetString("organ-printer-empty"),
                StyleClasses = { "LabelSubText" },
                HorizontalAlignment = HAlignment.Center,
            });
            return;
        }

        foreach (var product in _filtered)
        {
            var proto = _proto.Index<EntityPrototype>(product.Product);
            var nameText = proto.Name;
            if (string.IsNullOrWhiteSpace(nameText))
                nameText = proto.SetName ?? proto.ID;

            var row = new Button
            {
                ToggleMode = true,
                HorizontalExpand = true,
                MinHeight = 40,
                Margin = new Thickness(0, 0, 0, 2),
                ClipText = true,
            };
            row.Label.RemoveStyleClass(ContainerButton.StyleClassButton);
            row.Label.Align = Label.AlignMode.Left;
            row.Label.Margin = new Thickness(52, 0, 118, 0);
            row.Label.ClipText = true;
            row.Label.FontColorOverride = DeadSpaceStylePalette.Text;
            row.Label.MouseFilter = MouseFilterMode.Ignore;
            row.Text = nameText;

            var icon = new EntityPrototypeView
            {
                MinSize = new Vector2(40, 32),
                MaxSize = new Vector2(40, 32),
                HorizontalAlignment = HAlignment.Left,
                VerticalAlignment = VAlignment.Center,
                Margin = new Thickness(4, 0, 0, 0),
                MouseFilter = MouseFilterMode.Ignore,
                Scale = new Vector2(1.6f, 1.6f),
            };
            icon.SetPrototype(product.Product);
            row.AddChild(icon);

            var cost = new Label
            {
                Text = Loc.GetString("organ-printer-cost-short", ("cost", product.Cost)),
                FontColorOverride = Robust.Shared.Maths.Color.FromHex("#ffb13b"),
                HorizontalAlignment = HAlignment.Right,
                VerticalAlignment = VAlignment.Center,
                Margin = new Thickness(0, 0, 8, 0),
                MouseFilter = MouseFilterMode.Ignore,
            };
            row.AddChild(cost);

            var captured = product;
            row.OnPressed += _ => Select(captured);

            OrganList.AddChild(row);
        }
    }

    private void Select(OrganPrinterProduct product)
    {
        _selected = product;
        UpdateSelection();
        UpdateBottomPanel();
    }

    private void UpdateSelection()
    {
        PreviewContainer.Visible = _products.Count > 0;

        if (_selected is not { } selected)
        {
            PreviewSprite.SetPrototype(null);
            PreviewNameLabel.Text = string.Empty;
            PreviewDescLabel.SetMessage(FormattedMessage.Empty);
            PreviewHintLabel.Visible = _products.Count > 0;
            RefreshRowToggles();
            return;
        }

        PreviewHintLabel.Visible = false;
        var proto = _proto.Index<EntityPrototype>(selected.Product);
        var nameText = proto.Name;
        if (string.IsNullOrWhiteSpace(nameText))
            nameText = proto.SetName ?? proto.ID;
        PreviewSprite.SetPrototype(selected.Product);
        PreviewNameLabel.Text = nameText;
        PreviewNameLabel.FontColorOverride = DeadSpaceStylePalette.Text;
        PreviewDescLabel.SetMessage(FormattedMessage.FromMarkupPermissive(proto.Description));
        RefreshRowToggles();
    }

    private void RefreshRowToggles()
    {
        var i = 0;
        foreach (var child in OrganList.Children)
        {
            if (child is not Button row)
                continue;

            row.Pressed = _selected is { } selected && _filtered[i].Product == selected.Product && _filtered[i].Group == selected.Group;
            i++;
        }
    }

    private void UpdateBottomPanel()
    {
        BiomassLabel.Text = Loc.GetString("organ-printer-biomass-label", ("amount", _biomass));
        BiomassLabel.FontColorOverride = Robust.Shared.Maths.Color.FromHex("#7dffb0");

        if (_selected is not { } selected || _printing)
        {
            CostLabel.Text = _printing
                ? Loc.GetString("organ-printer-busy")
                : Loc.GetString("organ-printer-cost-none");
            CostLabel.FontColorOverride = Robust.Shared.Maths.Color.FromHex("#9aa79b");
            PrintButton.Disabled = true;
            return;
        }

        var cost = selected.Cost;
        var affordable = _biomass >= cost;

        CostLabel.Text = Loc.GetString("organ-printer-cost-label", ("cost", cost));
        CostLabel.FontColorOverride = affordable
            ? Robust.Shared.Maths.Color.FromHex("#ffb13b")
            : Robust.Shared.Maths.Color.FromHex("#ff6b6b");
        PrintButton.Disabled = !affordable;
    }
}
