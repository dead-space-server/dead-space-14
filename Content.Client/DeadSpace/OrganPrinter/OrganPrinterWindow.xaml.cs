using System.Linq;
using System.Numerics;
using Content.Shared.DeadSpace.OrganPrinter;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client.DeadSpace.OrganPrinter;

[GenerateTypedNameReferences]
public sealed partial class OrganPrinterWindow : DefaultWindow
{
    [Dependency] private readonly IPrototypeManager _proto = default!;

    public event Action<EntProtoId, OrganSpeciesGroup, int, int>? OnPrintPressed;
    public event Action<EntProtoId, bool, OrganSpeciesGroup>? OnGameStarted;
    public event Action<bool>? OnGameFailed;
    public event Action? OnEjectPressed;

    private readonly SplicingGameControl _game = new();

    private List<OrganPrinterProduct> _products = new();
    private List<OrganPrinterProduct> _filtered = new();
    private OrganSpeciesGroup? _groupFilter = OrganSpeciesGroup.Humanoid;
    private EntProtoId? _selected;
    private int _biomass;

    public OrganPrinterWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        PrintButton.OnPressed += _ =>
        {
            if (_selected is { } selected)
                ShowGame();
        };

        GameCanvasContainer.AddChild(_game);
        _game.HorizontalExpand = true;
        _game.VerticalExpand = true;
        _game.Visible = false;

        var groups = Enum.GetValues<OrganSpeciesGroup>().ToList();
        foreach (var group in groups)
            GroupFilter.AddItem(Loc.GetString($"organ-printer-group-{group.ToString().ToLowerInvariant()}"));
        GroupFilter.SelectId(0);
        GroupFilter.OnItemSelected += args =>
        {
            GroupFilter.SelectId(args.Id);
            _groupFilter = groups[args.Id];
            RebuildList();
        };

        GameFastButton.OnPressed += _ => StartGame(true);
        GameFineButton.OnPressed += _ => StartGame(false);
        GameAbortButton.OnPressed += _ => CloseGame();
        GameDoneButton.OnPressed += _ => CloseGame();

        EjectButton.OnPressed += _ => OnEjectPressed?.Invoke();

        _game.OnStatsChanged += (coverage, integrity, waste) =>
        {
            GameCoverageLabel.Text = Loc.GetString("organ-printer-game-coverage", ("percent", coverage));
            GameWasteLabel.Text = Loc.GetString("organ-printer-game-waste", ("count", waste));
            GameIntegrityLabel.Text = Loc.GetString("organ-printer-game-integrity", ("percent", integrity));
        };

        _game.OnFinished += (won, quality, waste) =>
        {
            GameFastButton.Visible = false;
            GameFineButton.Visible = false;
            GameAbortButton.Visible = false;
            GameDoneButton.Visible = true;
            GameResultLabel.Visible = true;
            GameModeHintLabel.Visible = false;

            if (won)
            {
                GameResultLabel.Text = Loc.GetString("organ-printer-game-win", ("quality", quality), ("waste", waste));
                if (_selected is { } product)
                {
                    var group = _filtered.FirstOrDefault(p => p.Product == product)?.Group ?? OrganSpeciesGroup.Humanoid;
                    OnPrintPressed?.Invoke(product, group, quality, waste);
                }
            }
            else
            {
                GameResultLabel.Text = Loc.GetString("organ-printer-game-lose");
                OnGameFailed?.Invoke(_game.FastMode);
            }
        };
    }

    public void UpdateState(OrganPrinterUpdateState state)
    {
        _biomass = state.Biomass;

        var changed = !_products.Select(p => (p.Product, p.Cost))
            .SequenceEqual(state.Products.Select(p => (p.Product, p.Cost)));
        _products = state.Products;

        if (changed)
        {
            if (_selected != null && _products.All(p => p.Product != _selected))
                _selected = null;
            RebuildList();
        }

        UpdateSelection();
        UpdateBottomPanel();
    }

    #region Мини-игра

    private void ShowGame()
    {
        MainContainer.Visible = false;
        GameOverlay.Visible = true;

        GameFastButton.Visible = true;
        GameFineButton.Visible = true;
        GameAbortButton.Visible = true;
        GameDoneButton.Visible = false;
        GameResultLabel.Visible = false;
        GameModeHintLabel.Visible = true;
        GameModeHintLabel.Text = Loc.GetString("organ-printer-game-select-mode");
        GameCoverageLabel.Text = string.Empty;
        GameWasteLabel.Text = string.Empty;
        GameIntegrityLabel.Text = string.Empty;
        GameTitleLabel.Text = Loc.GetString("organ-printer-game-splicing");

        _game.Visible = true;
        _game.Abort();

        if (_selected is { } product)
        {
            var name = _proto.Index<EntityPrototype>(product).Name;
            GameTitleLabel.Text = Loc.GetString("organ-printer-game-title", ("organ", name));
            _game.LoadSilhouette(product);
        }
    }

    private void StartGame(bool fast)
    {
        if (_selected is not { } product)
            return;

        var group = _products.FirstOrDefault(p => p.Product == product)?.Group ?? OrganSpeciesGroup.Humanoid;
        OnGameStarted?.Invoke(product, fast, group);

        GameModeHintLabel.Text = Loc.GetString("organ-printer-game-goal");
        _game.Start(product, fast);
    }

    private void CloseGame()
    {
        _game.Abort();
        _game.Visible = false;
        GameOverlay.Visible = false;
        MainContainer.Visible = true;
        UpdateBottomPanel();
    }

    #endregion

    private void RebuildList()
    {
        _filtered = _products
            .Where(p => _groupFilter == null || p.Group == _groupFilter)
            .ToList();

        OrganList.RemoveAllChildren();

        if (_filtered.Count == 0)
        {
            OrganList.AddChild(new Label
            {
                Text = Loc.GetString("organ-printer-empty"),
                StyleClasses = { "LabelSubText" },
                HorizontalAlignment = HAlignment.Center,
            });
            return;
        }

        foreach (var product in _filtered)
        {
            var row = new Button
            {
                ToggleMode = true,
                HorizontalExpand = true,
                Margin = new Thickness(0, 0, 0, 2),
            };

            var content = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                SeparationOverride = 8,
            };

            var iconBox = new PanelContainer
            {
                MinSize = new Vector2(44, 36),
                MaxSize = new Vector2(44, 36),
                RectClipContent = true,
                StyleClasses = { "DeadSpaceInset" },
            };

            var icon = new EntityPrototypeView
            {
                HorizontalExpand = true,
                VerticalExpand = true,
            };
            icon.SetPrototype(product.Product);
            icon.Scale = new Vector2(2, 2);
            iconBox.AddChild(icon);

            var name = new Label
            {
                Text = _proto.Index<EntityPrototype>(product.Product).Name,
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
                ClipText = true,
            };

            var cost = new Label
            {
                Text = Loc.GetString("organ-printer-cost-short", ("cost", product.Cost)),
                FontColorOverride = Color.FromHex("#ffb13b"),
                VerticalAlignment = VAlignment.Center,
            };

            content.AddChild(iconBox);
            content.AddChild(name);
            content.AddChild(cost);
            row.AddChild(content);

            var captured = product.Product;
            row.OnPressed += _ => Select(captured);

            OrganList.AddChild(row);
        }
    }

    private void Select(EntProtoId product)
    {
        _selected = product;
        UpdateSelection();
        UpdateBottomPanel();
    }

    private void UpdateSelection()
    {
        PreviewContainer.Visible = _products.Count > 0;

        if (_selected is not { } selected)
        {
            PreviewSprite.SetPrototype(null);
            PreviewNameLabel.Text = string.Empty;
            PreviewDescLabel.SetMessage(FormattedMessage.Empty);
            PreviewHintLabel.Visible = _products.Count > 0;
            RefreshRowToggles();
            return;
        }

        PreviewHintLabel.Visible = false;
        var proto = _proto.Index<EntityPrototype>(selected);
        PreviewSprite.SetPrototype(selected);
        PreviewNameLabel.Text = proto.Name;
        PreviewDescLabel.SetMessage(FormattedMessage.FromMarkupPermissive(proto.Description));
        RefreshRowToggles();
    }

    private void RefreshRowToggles()
    {
        var i = 0;
        foreach (var child in OrganList.Children)
        {
            if (child is not Button row)
                continue;

            row.Pressed = _selected != null && _filtered[i].Product == _selected;
            i++;
        }
    }

    private void UpdateBottomPanel()
    {
        BiomassLabel.Text = Loc.GetString("organ-printer-biomass-label", ("amount", _biomass));
        BiomassLabel.FontColorOverride = Color.FromHex("#7dffb0");

        if (_selected is not { } selected)
        {
            CostLabel.Text = Loc.GetString("organ-printer-cost-none");
            CostLabel.FontColorOverride = Color.FromHex("#9aa79b");
            PrintButton.Disabled = true;
            return;
        }

        var entry = _products.FirstOrDefault(p => p.Product == selected);
        var cost = entry?.Cost ?? 0;
        var affordable = _biomass >= cost;

        CostLabel.Text = Loc.GetString("organ-printer-cost-label", ("cost", cost));
        CostLabel.FontColorOverride = affordable ? Color.FromHex("#ffb13b") : Color.FromHex("#ff6b6b");
        PrintButton.Disabled = !affordable;
    }
}
