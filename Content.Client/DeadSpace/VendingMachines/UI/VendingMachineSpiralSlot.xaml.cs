using Content.Shared.Chemistry;
using Content.Shared.Chemistry.Components;
using Content.Shared.Chemistry.Components.SolutionManager;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.DeadSpace.VendingMachines.UI;

[GenerateTypedNameReferences]
public sealed partial class VendingMachineSpiralSlot : PanelContainer
{
    [Dependency] private readonly IEntityManager _entMan = default!;
    [Dependency] private readonly IPrototypeManager _prototypeManager = default!;

    private static readonly Color CoilLoaded = Color.FromHex("#b8bcc6");
    private static readonly Color CoilEmpty = Color.FromHex("#2c2f36");

    private readonly EntProtoId _proto;
    private readonly int _capacity;
    private EntityUid? _previewEntity;

    public VendingMachineSpiralSlot(EntProtoId proto, string code, string name, int capacity)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _proto = proto;
        _capacity = Math.Max(1, capacity);
        CodeLabel.Text = code;
        ToolTip = $"{code} — {name}";
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();

        if (_previewEntity != null || !_prototypeManager.HasIndex(_proto))
            return;

        _previewEntity = _entMan.Spawn(_proto);
        ApplySolutionVisuals(_previewEntity.Value);
        _entMan.System<SpriteSystem>().ForceUpdate(_previewEntity.Value);
        ItemPrototype.SetEntity(_previewEntity);
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        ItemPrototype.SetEntity(null);
        _entMan.TryQueueDeleteEntity(_previewEntity);
        _previewEntity = null;
    }

    private void ApplySolutionVisuals(EntityUid uid)
    {
        if (!_entMan.TryGetComponent(uid, out SolutionContainerVisualsComponent? visuals) ||
            !_entMan.TryGetComponent(uid, out SolutionContainerManagerComponent? manager) ||
            !_entMan.TryGetComponent(uid, out AppearanceComponent? appearance) ||
            manager.Solutions is not { Count: > 0 } solutions)
            return;

        var solutionName = visuals.SolutionName;
        Solution? solution = null;
        if (solutionName != null)
            solutions.TryGetValue(solutionName, out solution);

        if (solution == null)
        {
            foreach (var (name, soln) in solutions)
            {
                solutionName = name;
                solution = soln;
                break;
            }
        }

        if (solution == null || solutionName == null)
            return;

        var appearanceSystem = _entMan.System<AppearanceSystem>();
        appearanceSystem.SetData(uid, SolutionContainerVisuals.FillFraction, solution.FillFraction, appearance);
        appearanceSystem.SetData(uid, SolutionContainerVisuals.Color, solution.GetColor(_prototypeManager), appearance);
        appearanceSystem.SetData(uid, SolutionContainerVisuals.SolutionName, solutionName, appearance);

        if (solution.GetPrimaryReagentId() is { } reagent)
            appearanceSystem.SetData(uid, SolutionContainerVisuals.BaseOverride, reagent.ToString(), appearance);
    }

    public void SetAmount(uint amount)
    {
        AmountLabel.Text = $"×{amount}";
        ItemPrototype.Modulate = amount == 0 ? Color.White.WithAlpha(0.2f) : Color.White;

        SpiralCoils.RemoveAllChildren();
        for (var i = 0; i < _capacity; i++)
        {
            SpiralCoils.AddChild(new PanelContainer
            {
                MinSize = new(6, 8),
                PanelOverride = new StyleBoxFlat(i < amount ? CoilLoaded : CoilEmpty),
            });
        }
    }
}
