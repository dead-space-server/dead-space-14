using Content.Client.DeadSpace.Stylesheets;
using Content.Shared.Chemistry;
using Content.Shared.Chemistry.Components;
using Content.Shared.Chemistry.Components.SolutionManager;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.DeadSpace.VendingMachines.UI;

[GenerateTypedNameReferences]
public sealed partial class VendingMachineSpiralSlot : PanelContainer
{
    [Dependency] private IEntityManager _entMan = default!;
    [Dependency] private IPrototypeManager _prototypeManager = default!;

    private static readonly Color CoilLoaded = Color.FromHex("#b8bcc6");
    private static readonly Color CoilEmpty = Color.FromHex("#2c2f36");
    private static readonly Color NameColor = Color.FromHex("#d8dce4");
    private static readonly Color PriceColor = Color.FromHex("#e8c547");
    private static readonly Color SlotBackground = Color.FromHex("#16181d");
    private static readonly Color SlotBorder = Color.FromHex("#30343c");
    private static readonly Color BadgeBackground = Color.FromHex("#c9b458");
    private static readonly Color BadgeText = Color.FromHex("#111111");

    private readonly EntProtoId? _proto;
    private readonly int _capacity;
    private EntityUid? _previewEntity;
    private uint? _amount;

    public string ItemName { get; }

    public VendingMachineSpiralSlot(EntProtoId? proto, string code, string name, int capacity)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _proto = proto;
        _capacity = Math.Max(1, capacity);
        ItemName = name;
        NameLabel.Text = name;
        CodeLabel.Text = code;
        ToolTip = $"{code} — {name}";
        RefreshStyle();
    }

    /// <summary>
    /// Frame, badge and colours for the current interface style: square projected frames from the palette in the
    /// Dead Space style, the original vending machine look in the others.
    /// </summary>
    public void RefreshStyle()
    {
        if (DeadSpaceStylePalette.Hologram)
        {
            PanelOverride = DeadSpaceStyleBoxes.Holo(DeadSpaceStylePalette.ListItem, DeadSpaceStylePalette.BorderDark);
            CodeBadge.PanelOverride = DeadSpaceStyleBoxes.Holo(
                Color.Transparent,
                DeadSpaceStylePalette.BorderHeader,
                horizontalMargin: 6);
            NameLabel.FontColorOverride = DeadSpaceStylePalette.Text;
            PriceLabel.FontColorOverride = DeadSpaceStylePalette.Amber;
            CodeLabel.FontColorOverride = DeadSpaceStylePalette.CyanBright;
        }
        else
        {
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = SlotBackground,
                BorderColor = SlotBorder,
                BorderThickness = new Thickness(1),
            };
            CodeBadge.PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = BadgeBackground,
                ContentMarginLeftOverride = 6,
                ContentMarginRightOverride = 6,
            };
            NameLabel.FontColorOverride = NameColor;
            PriceLabel.FontColorOverride = PriceColor;
            CodeLabel.FontColorOverride = BadgeText;
        }

        UpdateCoils();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();

        if (_previewEntity != null || _proto is not { } proto || !_prototypeManager.HasIndex(proto))
            return;

        _previewEntity = _entMan.Spawn(proto);
        ApplySolutionVisuals(_previewEntity.Value);
        _entMan.System<SpriteSystem>().ForceUpdate(_previewEntity.Value);
        ItemPrototype.SetEntity(_previewEntity);
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        ItemPrototype.SetEntity(null);
        _entMan.TryQueueDeleteEntity(_previewEntity);
        _previewEntity = null;
    }

    private void ApplySolutionVisuals(EntityUid uid)
    {
        if (!_entMan.TryGetComponent(uid, out SolutionContainerVisualsComponent? visuals) ||
            !_entMan.TryGetComponent(uid, out SolutionContainerManagerComponent? manager) ||
            !_entMan.TryGetComponent(uid, out AppearanceComponent? appearance) ||
            manager.Solutions is not { Count: > 0 } solutions)
            return;

        var solutionName = visuals.SolutionName;
        Solution? solution = null;
        if (solutionName != null)
            solutions.TryGetValue(solutionName, out solution);

        if (solution == null)
        {
            foreach (var (name, soln) in solutions)
            {
                solutionName = name;
                solution = soln;
                break;
            }
        }

        if (solution == null || solutionName == null)
            return;

        var appearanceSystem = _entMan.System<AppearanceSystem>();
        appearanceSystem.SetData(uid, SolutionContainerVisuals.FillFraction, solution.FillFraction, appearance);
        appearanceSystem.SetData(uid, SolutionContainerVisuals.Color, solution.GetColor(_prototypeManager), appearance);
        appearanceSystem.SetData(uid, SolutionContainerVisuals.SolutionName, solutionName, appearance);

        if (solution.GetPrimaryReagentId() is { } reagent)
            appearanceSystem.SetData(uid, SolutionContainerVisuals.BaseOverride, reagent.ToString(), appearance);
    }

    public void SetPrice(string? price)
    {
        PriceLabel.Visible = price != null;
        PriceLabel.Text = price ?? string.Empty;
    }

    public void SetAmount(uint? amount)
    {
        _amount = amount;
        AmountLabel.Text = amount is { } count ? $"×{count}" : "×∞";
        ItemPrototype.Modulate = amount == 0 ? Color.White.WithAlpha(0.2f) : Color.White;
        UpdateCoils();
    }

    private void UpdateCoils()
    {
        var hologram = DeadSpaceStylePalette.Hologram;
        var loaded = hologram ? DeadSpaceStylePalette.Cyan : CoilLoaded;
        var empty = hologram ? DeadSpaceStylePalette.BorderDark : CoilEmpty;

        SpiralCoils.RemoveAllChildren();
        for (var i = 0; i < _capacity; i++)
        {
            SpiralCoils.AddChild(new PanelContainer
            {
                MinSize = new(6, 8),
                PanelOverride = new StyleBoxFlat(_amount == null || i < _amount ? loaded : empty),
            });
        }
    }
}
