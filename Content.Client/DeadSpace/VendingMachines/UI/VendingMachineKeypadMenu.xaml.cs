using System.Linq;
using System.Text;
using Content.Client.Stylesheets;
using Content.Client.UserInterface.Controls;
using Content.Shared.Labels.Components;
using Content.Shared.VendingMachines;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client.DeadSpace.VendingMachines.UI;

public sealed record VendingMachineKeypadEntry(
    EntProtoId? Prototype,
    string Name,
    uint? Amount,
    string? Price = null,
    bool Affordable = true);

[GenerateTypedNameReferences]
public sealed partial class VendingMachineKeypadMenu : FancyWindow
{
    [Dependency] private IComponentFactory _componentFactory = default!;
    [Dependency] private ILocalizationManager _loc = default!;
    [Dependency] private IPrototypeManager _prototypeManager = default!;

    private readonly List<VendingMachineSpiralSlot> _slots = new();
    private readonly List<VendingMachineKeypadEntry> _entries = new();
    private readonly StringBuilder _input = new();

    private Button _approveButton = default!;
    private const float SlotWidth = 146f;
    private const float ScrollBarWidth = 14f;
    private const float SlotMargin = 6f;

    private float _slotWidth = SlotWidth - SlotMargin;

    private int _maxColumns = 4;
    private int _codeLength = 2;
    private int _spiralCapacity = 8;
    private bool _enabled;
    private string _search = string.Empty;

    public event Action<int>? OnCodeApproved;
    public event Action? OnWithdrawPressed;

    public VendingMachineKeypadMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        SearchBar.OnTextChanged += args =>
        {
            _search = args.Text.Trim().ToLowerInvariant();
            ApplySearch();
        };
        WithdrawButton.OnPressed += _ => OnWithdrawPressed?.Invoke();

        BuildKeypad();
        ResetInput();
    }

    public void Configure(int columns, int spiralCapacity)
    {
        _maxColumns = Math.Max(1, columns);
        _spiralCapacity = spiralCapacity;
        UpdateColumns();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateColumns();
    }

    private void UpdateColumns()
    {
        var available = SpiralScroll.Width - ScrollBarWidth;
        var fit = available > 0 ? (int) (available / SlotWidth) : _maxColumns;
        var columns = Math.Clamp(fit, 1, _maxColumns);

        if (SpiralGrid.Columns != columns)
            SpiralGrid.Columns = columns;

        var slotWidth = available > 0
            ? MathF.Floor(available / columns) - SlotMargin
            : SlotWidth - SlotMargin;

        if (MathHelper.CloseTo(slotWidth, _slotWidth))
            return;

        _slotWidth = slotWidth;
        foreach (var slot in _slots)
            slot.SetWidth = _slotWidth;
    }

    private void BuildKeypad()
    {
        for (var digit = 1; digit <= 9; digit++)
            AddDigitButton(digit);

        var cancel = new Button
        {
            Text = Loc.GetString("vending-machine-keypad-cancel"),
            MinSize = new(56, 40),
            StyleClasses = { StyleNano.ButtonCaution },
        };
        cancel.OnPressed += _ => ResetInput();
        KeypadGrid.AddChild(cancel);

        AddDigitButton(0);

        _approveButton = new Button
        {
            Text = Loc.GetString("vending-machine-keypad-approve"),
            MinSize = new(56, 40),
            StyleClasses = { StyleNano.StyleClassButtonColorGreen },
        };
        _approveButton.OnPressed += _ => Approve();
        KeypadGrid.AddChild(_approveButton);
    }

    private void AddDigitButton(int digit)
    {
        var button = new Button
        {
            Text = digit.ToString(),
            MinSize = new(56, 40),
        };
        button.OnPressed += _ => PressDigit(digit);
        KeypadGrid.AddChild(button);
    }

    public void Populate(List<VendingMachineInventoryEntry> inventory, bool enabled)
    {
        Populate(ToEntries(inventory), enabled);
    }

    public void UpdateAmounts(List<VendingMachineInventoryEntry> inventory, bool enabled)
    {
        SetEntries(ToEntries(inventory), enabled);
    }

    public void Populate(IReadOnlyList<VendingMachineKeypadEntry> entries, bool enabled)
    {
        _enabled = enabled;
        _slots.Clear();
        _entries.Clear();
        SpiralGrid.RemoveAllChildren();

        _codeLength = Math.Max(2, entries.Count.ToString().Length);

        for (var i = 0; i < entries.Count; i++)
        {
            var entry = entries[i];
            var slot = new VendingMachineSpiralSlot(entry.Prototype, FormatCode(i), entry.Name, _spiralCapacity);
            slot.SetAmount(entry.Amount);
            slot.SetPrice(entry.Price);

            _slots.Add(slot);
            _entries.Add(entry);
            slot.SetWidth = _slotWidth;
            SpiralGrid.AddChild(slot);
        }

        EmptyLabel.Visible = entries.Count == 0;
        ApplySearch();
        ResetInput();
    }

    public void SetEntries(IReadOnlyList<VendingMachineKeypadEntry> entries, bool enabled)
    {
        if (entries.Count != _entries.Count ||
            entries.Where((entry, i) => entry.Prototype != _entries[i].Prototype || entry.Name != _entries[i].Name).Any())
        {
            Populate(entries, enabled);
            return;
        }

        _enabled = enabled;
        for (var i = 0; i < entries.Count; i++)
        {
            _entries[i] = entries[i];
            _slots[i].SetAmount(entries[i].Amount);
            _slots[i].SetPrice(entries[i].Price);
        }

        UpdateDisplay();
    }

    public void SetBalance(string? balance)
    {
        BalanceDisplay.Visible = !string.IsNullOrEmpty(balance);
        BalanceDisplay.Text = balance ?? string.Empty;
    }

    public void SetWithdrawVisible(bool visible)
    {
        WithdrawButton.Visible = visible;
    }

    private List<VendingMachineKeypadEntry> ToEntries(List<VendingMachineInventoryEntry> inventory)
    {
        var entries = new List<VendingMachineKeypadEntry>(inventory.Count);
        foreach (var entry in inventory)
        {
            var name = _prototypeManager.Resolve(entry.ID, out var proto) ? GetItemName(proto) : entry.ID.Id;
            entries.Add(new VendingMachineKeypadEntry(entry.ID, name, entry.Amount));
        }

        return entries;
    }

    private void ApplySearch()
    {
        foreach (var slot in _slots)
        {
            slot.Visible = string.IsNullOrEmpty(_search) ||
                           slot.ItemName.ToLowerInvariant().Contains(_search) ||
                           slot.ToolTip?.ToLowerInvariant().Contains(_search) == true;
        }
    }

    private void PressDigit(int digit)
    {
        if (_input.Length >= _codeLength)
            _input.Clear();

        _input.Append(digit);
        UpdateDisplay();
    }

    private void Approve()
    {
        if (!_enabled)
            return;

        if (_input.Length != _codeLength || !TryGetIndex(out var index))
        {
            Reject("vending-machine-keypad-invalid-code");
            return;
        }

        var entry = _entries[index];
        if (entry.Amount == 0)
        {
            Reject("vending-machine-keypad-out-of-stock");
            return;
        }

        if (!entry.Affordable)
        {
            Reject("vending-machine-keypad-no-funds");
            return;
        }

        OnCodeApproved?.Invoke(index);
        StatusDisplay.Text = Loc.GetString("vending-machine-keypad-vending", ("item", entry.Name));
        _input.Clear();
        UpdateCode();
    }

    private void Reject(string locId)
    {
        SetStatus(locId);
        _input.Clear();
        UpdateCode();
    }

    private void ResetInput()
    {
        _input.Clear();
        UpdateDisplay();
    }

    private void UpdateDisplay()
    {
        UpdateCode();
        _approveButton.Disabled = !_enabled;

        if (!_enabled)
            SetStatus("vending-machine-keypad-busy");
        else if (_input.Length == _codeLength && TryGetIndex(out var index))
            StatusDisplay.Text = FormatEntryStatus(_entries[index]);
        else
            SetStatus("vending-machine-keypad-enter-code");
    }

    private static string FormatEntryStatus(VendingMachineKeypadEntry entry)
    {
        var text = entry.Amount is { } amount ? $"{entry.Name} ×{amount}" : entry.Name;
        return entry.Price != null ? $"{text} — {entry.Price}" : text;
    }

    private void UpdateCode()
    {
        CodeDisplay.Text = Loc.GetString("vending-machine-keypad-code",
            ("code", _input.ToString().PadRight(_codeLength, '_')));
    }

    private void SetStatus(string locId)
    {
        StatusDisplay.Text = Loc.GetString(locId);
    }

    private bool TryGetIndex(out int index)
    {
        index = -1;
        if (!int.TryParse(_input.ToString(), out var code))
            return false;

        index = code - 1;
        return index >= 0 && index < _entries.Count;
    }

    private string GetItemName(EntityPrototype prototype)
    {
        if (!prototype.TryGetComponent<LabelComponent>(out var label, _componentFactory) ||
            label.CurrentLabel is not { } labelText)
            return prototype.Name;

        var localizedLabel = _loc.TryGetString(labelText, out var localized) ? localized : labelText;
        return _loc.GetString("comp-label-format",
            ("baseName", prototype.Name),
            ("label", localizedLabel));
    }

    private string FormatCode(int index)
    {
        return (index + 1).ToString().PadLeft(_codeLength, '0');
    }
}
