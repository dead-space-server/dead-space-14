using System.Numerics;
using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared.DeadSpace.Administration;
using Content.Shared.Roles;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;

namespace Content.Client.DeadSpace.Administration.UI;

[GenerateTypedNameReferences]
public sealed partial class TimeTransferWindow : FancyWindow
{
    private const float IconSize = 24f;
    [Dependency] private readonly IEntityManager _entManager = default!;
    [Dependency] private readonly IPrototypeManager _prototype = default!;

    private readonly SpriteSystem _spriteSystem;

    private sealed record RoleRow(string Tracker, string Name, BoxContainer Row, LineEdit Input, CheckBox Check);

    private readonly List<RoleRow> _rows = new();

    public event Action<string, TimeTransferMode, int?, List<TimeTransferEntry>>? OnSubmit;

    public TimeTransferWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _spriteSystem = _entManager.System<SpriteSystem>();

        BuildRoleRows();

        OverallLine.IsValid = IsValidMinutes;
        GroupLine.IsValid = IsValidMinutes;
        GroupCheck.OnToggled += args => SetGrouping(args.Pressed);
        SearchLine.OnTextChanged += args => ApplyFilter(args.Text);
        AddButton.OnPressed += _ => Submit(TimeTransferMode.Add);
        SetButton.OnPressed += _ => Submit(TimeTransferMode.Set);
    }

    private void BuildRoleRows()
    {
        var seen = new HashSet<string>();

        foreach (var job in _prototype.EnumeratePrototypes<JobPrototype>().OrderBy(j => j.LocalizedName))
        {
            var tracker = job.PlayTimeTracker.ToString();

            if (!seen.Add(tracker))
                continue;

            var input = new LineEdit
            {
                MinSize = new Vector2(90, 0),
                PlaceHolder = "0",
                IsValid = IsValidMinutes,
            };

            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 6,
            };

            if (_prototype.TryIndex(job.Icon, out var jobIcon))
            {
                var texture = _spriteSystem.Frame0(jobIcon.Icon);
                var scale = IconSize / MathF.Max(texture.Width, texture.Height);
                var icon = new TextureRect()
                {
                    Texture = texture,
                    TextureScale = new Vector2(scale, scale),
                    Stretch = TextureRect.StretchMode.KeepCentered,
                    MinSize = new Vector2(IconSize, IconSize),
                    MaxSize = new Vector2(IconSize, IconSize),
                    VerticalAlignment = VAlignment.Center,
                    Margin = new Thickness(0, 0, 4, 0)
                };
                row.AddChild(icon);
            }
            else
            {
                row.AddChild(new Control { MinSize = new Vector2(IconSize + 4, IconSize) });
            }

            row.AddChild(new Label
            {
                Text = job.LocalizedName,
                HorizontalExpand = true,
                ClipText = true,
            });
            row.AddChild(input);

            var check = new CheckBox { Visible = false };
            row.AddChild(check);

            RolesContainer.AddChild(row);
            _rows.Add(new RoleRow(tracker, job.LocalizedName, row, input, check));
        }
    }

    private void ApplyFilter(string text)
    {
        var query = text.Trim();

        foreach (var r in _rows)
        {
            r.Row.Visible = query.Length == 0
                            || r.Name.Contains(query, StringComparison.CurrentCultureIgnoreCase)
                            || r.Tracker.Contains(query, StringComparison.OrdinalIgnoreCase);
        }
    }

    private void Submit(TimeTransferMode mode)
    {
        var entries = new List<TimeTransferEntry>();

        if (GroupCheck.Pressed)
        {
            if (int.TryParse(GroupLine.Text, out var groupMinutes))
            {
                foreach (var r in _rows)
                {
                    if (r.Check.Pressed)
                        entries.Add(new TimeTransferEntry(r.Tracker, groupMinutes));
                }
            }
        }
        else
        {
            foreach (var r in _rows)
            {
                if (int.TryParse(r.Input.Text, out var minutes))
                    entries.Add(new TimeTransferEntry(r.Tracker, minutes));
            }
        }

        int? overall = int.TryParse(OverallLine.Text, out var parsed) ? parsed : null;

        OnSubmit?.Invoke(CkeyLine.Text.Trim(), mode, overall, entries);
    }

    public void SetStatus(string? text, bool success)
    {
        StatusLabel.Visible = !string.IsNullOrEmpty(text);
        StatusLabel.Text = text ?? string.Empty;
        StatusLabel.FontColorOverride = success ? Color.LightGreen : Color.OrangeRed;

        if (!success)
            return;

        OverallLine.Text = string.Empty;
        GroupLine.Text = string.Empty;

        foreach (var r in _rows)
        {
            r.Input.Text = string.Empty;
            r.Check.Pressed = false;
        }
    }

    private static bool IsValidMinutes(string text)
    {
        return text.Length == 0
               || text == "-"
               || text.Length <= 7 && int.TryParse(text, out _);
    }

    private void SetGrouping(bool grouped)
    {
        GroupLine.Visible = grouped;

        foreach (var r in _rows)
        {
            r.Input.Visible = !grouped;
            r.Check.Visible = grouped;
        }
    }
}
