using Content.Shared.DeadSpace.OrganDamage;
using Content.Shared.DeadSpace.Microscope;
using Content.Shared.FixedPoint;
using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client.DeadSpace.Microscope.UI;

[GenerateTypedNameReferences]
public sealed partial class MicroscopeWindow : DefaultWindow
{
    public event Action? EjectOrganPressed;

    public MicroscopeWindow()
    {
        RobustXamlLoader.Load(this);

        EjectButton.OnPressed += _ => EjectOrganPressed?.Invoke();
        OrganView.OnWoundClicked += wound => WoundClicked?.Invoke(wound);
    }

    public event Action<OrganWound>? WoundClicked;

    public void UpdateState(MicroscopeBoundUserInterfaceState state)
    {
        var hasOrgan = state.Organ != null && state.Organ.Value != NetEntity.Invalid;

        if (hasOrgan)
        {
            OrganView.SetOrgan(state.Organ!.Value, state.Wounds);
            OrganNameLabel.Text = state.OrganName;

            var fraction = state.MaxDamage > FixedPoint2.Zero
                ? (state.Damage / state.MaxDamage).Float()
                : 0f;
            DamageBar.Value = Math.Clamp(fraction, 0f, 1f);

            if (state.Dead)
            {
                StatusLabel.Text = Loc.GetString("microscope-ui-organ-dead");
                StatusLabel.ModulateSelfOverride = new Color(0.9f, 0.25f, 0.25f);
            }
            else
            {
                StatusLabel.Text = Loc.GetString(
                    "microscope-ui-organ-damage",
                    ("damage", state.Damage.Float()),
                    ("max", state.MaxDamage.Float()));
                StatusLabel.ModulateSelfOverride = Color.White;
            }
        }
        else
        {
            OrganView.SetOrgan(null, new List<OrganWound>());
            OrganNameLabel.Text = Loc.GetString("microscope-ui-empty");
            DamageBar.Value = 0f;
            StatusLabel.Text = string.Empty;
        }

        EjectButton.Disabled = !hasOrgan;
    }
}
