    #region Options

    private void BuildGroupPanel()
    {
        // The group containers keep their state; only the sections around them are rebuilt.
        foreach (var container in _groupContainers.Values)
        {
            container.Orphan();
        }

        GroupPanel.RemoveAllChildren();

        var title = Loc.GetString("hologram-loadout-inventory");
        var slotButton = _slotButtons.FirstOrDefault(b => b.Slot == _selectedSlot);
        if (_selectedSlot != null && slotButton != null)
            title = Loc.GetString("hologram-loadout-inventory-slot", ("inventory", title), ("slot", SlotCaption(_selectedSlot, _selectedSlot)));

        InventoryTitle.Text = Caps(title);

        if (_slotMap.Groups.Count == 0)
        {
            GroupPanel.AddChild(CreateHint(Loc.GetString("hologram-loadout-no-groups")));
            return;
        }

        if (_selectedSlot != null)
        {
            foreach (var group in _slotMap.GetGroups(_selectedSlot))
            {
                GroupPanel.AddChild(CreateGroupSection(group, false));
            }
        }

        var unmapped = _slotMap.Groups.Where(g => !_slotMap.MapsToAny(g, _shownSlots)).ToList();

        if (_selectedSlot == null && unmapped.Count < _slotMap.Groups.Count)
            GroupPanel.AddChild(CreateHint(Loc.GetString("hologram-loadout-select-slot")));

        if (unmapped.Count == 0)
            return;

        GroupPanel.AddChild(new Label
        {
            Text = Caps(Loc.GetString("hologram-loadout-extra")),
            StyleClasses = { DeadSpaceStyleClass.SectionTitle },
            Margin = new Thickness(2, 8, 2, 2),
        });

        foreach (var group in unmapped)
        {
            GroupPanel.AddChild(CreateGroupSection(group, true));
        }
    }

    private Control CreateGroupSection(LoadoutGroupPrototype group, bool collapsible)
    {
        var section = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
        };

        var container = _groupContainers[group.ID];
        var count = _loadout.SelectedLoadouts.TryGetValue(group.ID, out var selected) ? selected.Count : 0;
        var title = Loc.GetString("hologram-loadout-group-title",
            ("name", Loc.GetString(group.Name)),
            ("count", count),
            ("max", group.MaxLimit));

        if (!collapsible)
        {
            container.Visible = true;
            section.AddChild(new PanelContainer
            {
                StyleClasses = { DeadSpaceStyleClass.ListHeader },
                Children =
                {
                    new Label
                    {
                        Text = Caps(title),
                        ClipText = true,
                        StyleClasses = { DeadSpaceStyleClass.SectionTitle },
                    },
                },
            });
            section.AddChild(container);
            return section;
        }

        var expanded = ExpandedGroups.Contains(group.ID);
        container.Visible = expanded;

        var toggle = new Button
        {
            Text = ToggleText(title, expanded),
            TextAlign = Label.AlignMode.Left,
            ToggleMode = true,
            Pressed = expanded,
            HorizontalExpand = true,
            ClipText = true,
        };
        toggle.OnToggled += args =>
        {
            container.Visible = args.Pressed;
            toggle.Text = ToggleText(title, args.Pressed);

            if (args.Pressed)
                ExpandedGroups.Add(group.ID);
            else
                ExpandedGroups.Remove(group.ID);
        };

        section.AddChild(toggle);
        section.AddChild(container);
        return section;
    }

    private static string ToggleText(string title, bool expanded)
    {
        return (expanded ? "▼ " : "▶ ") + title;
    }

    private static Control CreateHint(string text)
    {
        return new Label
        {
            Text = text,
            StyleClasses = { StyleClass.LabelSubText },
            Margin = new Thickness(2, 4),
        };
    }

    #endregion

    /// <summary>The "Dead Space" style writes titles and captions in capitals; other styles keep the source text.</summary>
    private static string Caps(string text)
    {
        return DeadSpaceStylePalette.Hologram ? text.ToUpper(CultureInfo.CurrentCulture) : text;
    }

    private void OnInterfaceStyleChanged(string _)
    {
        // Colours follow the palette on their own; captions change case with the style.
        RebuildRoles();
        UpdateHeader();
        BuildSlots();
        BuildGroupPanel();
    }

    private sealed record SlotEntry(
        string Slot,
        string Caption,
        EntityUid? Item,
        IReadOnlyList<LoadoutGroupPrototype> Groups);
