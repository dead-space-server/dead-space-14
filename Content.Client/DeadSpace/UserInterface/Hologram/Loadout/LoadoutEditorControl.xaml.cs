    #region Roles

    /// <summary>The filter of the list this screen shows: antagonists in the antagonists tab, jobs otherwise.</summary>
    private string RoleFilter
    {
        get => AntagScreen ? _antagFilter : _jobFilter;
        set
        {
            if (AntagScreen)
                _antagFilter = value;
            else
                _jobFilter = value;
        }
    }

    private bool MatchesFilter(string text)
    {
        var filter = RoleFilter.Trim();
        return filter.Length == 0 || text.Contains(filter, StringComparison.CurrentCultureIgnoreCase);
    }

    private void RebuildRoles()
    {
        RoleList.RemoveAllChildren();

        if (AntagScreen)
        {
            RebuildAntags();
            return;
        }

        var departments = _protoManager.EnumeratePrototypes<DepartmentPrototype>()
            .Where(department => !department.EditorHidden)
            .ToList();
        departments.Sort(DepartmentUIComparer.Instance);
        JobUIComparer.TryCreate(_protoManager, null, out var comparer);

        foreach (var department in departments)
        {
            var jobs = department.Roles
                .Select(id => _protoManager.TryIndex(id, out var job) ? job : null)
                .OfType<JobPrototype>()
                .Where(job => job.SetPreference &&
                              _protoManager.HasIndex<RoleLoadoutPrototype>(LoadoutSystem.GetJobPrototype(job.ID)))
                .ToArray();

            // A department name match keeps the whole department; otherwise only matching jobs stay.
            var departmentName = Loc.GetString(department.Name);
            if (!MatchesFilter(departmentName))
                jobs = jobs.Where(job => MatchesFilter(job.LocalizedName)).ToArray();

            if (jobs.Length == 0)
                continue;

            if (comparer != null)
                Array.Sort(jobs, comparer);

            RoleList.AddChild(CreateRoleHeader(departmentName));

            foreach (var job in jobs)
            {
                Texture? icon = null;
                if (_protoManager.Resolve(job.Icon, out var jobIcon))
                    icon = _sprite.Frame0(jobIcon.Icon);

                var selected = _antag == null && LoadoutSystem.GetJobPrototype(job.ID) == _roleProto.ID;
                var priority = Profile.JobPriorities.GetValueOrDefault(new ProtoId<JobPrototype>(job.ID), JobPriority.Never);

                RoleList.AddChild(CreateRoleButton(job.LocalizedName, icon, selected, priority == JobPriority.Never, job, PriorityMarker(priority)));
            }
        }

        // The jobs tab is about jobs; antagonist loadouts keep their own window.
        if (_embedded)
            return;

        var antags = _protoManager.EnumeratePrototypes<AntagPrototype>()
            .Where(antag => antag.SetPreference &&
                            antag.RoleLoadout is { } roleLoadout &&
                            _protoManager.HasIndex(roleLoadout))
            .OrderBy(antag => Loc.GetString(antag.Name))
            .ToList();

        if (antags.Count == 0)
            return;

        RoleList.AddChild(CreateRoleHeader(Loc.GetString("hologram-loadout-antagonists")));

        foreach (var antag in antags)
        {
            var wanted = Profile.AntagPreferences.Contains(antag.ID);
            RoleList.AddChild(CreateRoleButton(Loc.GetString(antag.Name), null, _antag?.ID == antag.ID, !wanted, antag, null));
        }
    }

    /// <summary>Every antagonist that can be wanted, by name, each marked when the character wants it.</summary>
    private void RebuildAntags()
    {
        var antags = _protoManager.EnumeratePrototypes<AntagPrototype>()
            .Where(antag => antag.SetPreference && MatchesFilter(Loc.GetString(antag.Name)))
            .OrderBy(antag => Loc.GetString(antag.Name))
            .ToList();

        RoleList.AddChild(CreateRoleHeader(Loc.GetString("hologram-loadout-antagonists")));

        foreach (var antag in antags)
        {
            var wanted = Profile.AntagPreferences.Contains(antag.ID);
            var marker = wanted
                ? (Loc.GetString("hologram-loadout-antag-wanted-short"), DeadSpaceStyleClass.SectionTitle)
                : ((string, string)?) null;

            RoleList.AddChild(CreateRoleButton(Loc.GetString(antag.Name), null, _antag?.ID == antag.ID, !wanted, antag, marker));
        }
    }

    /// <summary>The job's priority at the end of its row; "never" is already shown by the muted name.</summary>
    private static (string Text, string StyleClass)? PriorityMarker(JobPriority priority)
    {
        if (priority == JobPriority.Never)
            return null;

        var text = Loc.GetString($"hologram-loadout-priority-short-{priority.ToString().ToLowerInvariant()}");
        var style = priority switch
        {
            JobPriority.High => DeadSpaceStyleClass.SectionTitle,
            JobPriority.Medium => StyleClass.LabelKeyText,
            _ => StyleClass.LabelSubText,
        };

        return (text, style);
    }

    private Control CreateRoleHeader(string text)
    {
        return new PanelContainer
        {
            StyleClasses = { DeadSpaceStyleClass.ListHeader },
            Margin = new Thickness(0, 4, 0, 0),
            Children =
            {
                new Label
                {
                    Text = Caps(text),
                    ClipText = true,
                    StyleClasses = { DeadSpaceStyleClass.SectionTitle },
                },
            },
        };
    }

    private Control CreateRoleButton(
        string name,
        Texture? icon,
        bool selected,
        bool muted,
        object role,
        (string Text, string StyleClass)? marker)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 6,
        };

        if (icon != null)
        {
            row.AddChild(new TextureRect
            {
                Texture = icon,
                TextureScale = new Vector2(2, 2),
                VerticalAlignment = VAlignment.Center,
            });
        }

        var label = new Label
        {
            Text = name,
            ClipText = true,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
        };

        // Roles the character never plays stay available but read as secondary.
        if (muted && !selected)
            label.StyleClasses.Add(StyleClass.LabelWeak);

        row.AddChild(label);

        // The role's state at the end of the row: job priority or a wanted antagonist.
        if (marker is { } shown)
        {
            row.AddChild(new Label
            {
                Text = Caps(shown.Text),
                VerticalAlignment = VAlignment.Center,
                StyleClasses = { shown.StyleClass },
            });
        }

        var button = new ContainerButton
        {
            StyleClasses = { ContainerButton.StyleClassButton },
            HorizontalExpand = true,
            Pressed = selected,
            Children = { row },
        };

        if (!selected)
            button.OnPressed += _ => Defer(() => RaiseRole(role));

        return button;
    }

