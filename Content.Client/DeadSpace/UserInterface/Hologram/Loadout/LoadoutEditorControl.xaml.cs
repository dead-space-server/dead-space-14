    /// <summary>Refreshes the options, the doll and the slots after the loadout changed.</summary>
    public void RefreshLoadouts(RoleLoadout loadout, ICommonSession session, IDependencyCollection collection)
    {
        _loadout = loadout;

        foreach (var container in _groupContainers.Values)
        {
            container.RefreshLoadouts(Profile, loadout, session, collection);
        }

        RebuildEquipment();
    }

    /// <summary>
    /// Raises an action outside of input handling and frame updates: the editor replaces this control in response,
    /// which must not happen while the UI tree is being walked.
    /// </summary>
    private void Defer(Action action)
    {
        if (_pendingAction != null)
            return;

        _pendingAction = action;
        global::Robust.Shared.Timing.Timer.Spawn(0, () =>
        {
            var pending = _pendingAction;
            _pendingAction = null;

            if (!Disposed)
                pending?.Invoke();
        });
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);
        if (!disposing)
            return;

        _cfg.UnsubValueChanged(CCCCVars.InterfaceStyle, OnInterfaceStyleChanged);

        // Containers of groups that aren't shown right now are outside the tree; they own preview entities.
        foreach (var container in _groupContainers.Values)
        {
            container.Dispose();
        }

        DeleteEntities();
    }

