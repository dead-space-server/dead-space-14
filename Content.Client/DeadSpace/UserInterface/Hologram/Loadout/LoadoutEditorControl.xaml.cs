        UnsavedLabel.Text = Loc.GetString("hologram-loadout-unsaved");
        ResetButton.OnPressed += _ => Defer(() => OnResetRequested?.Invoke());
        SaveButton.OnPressed += _ => Defer(() => OnSaveRequested?.Invoke());
        SetUnsaved(false);

        if (embedded)
        {
            // The tab is narrower than the window and the editor has its own save/reset: tighter columns, no bar.
            BottomBar.Visible = false;
            RolePanel.SetWidth = 200;
            InventoryPanel.SetWidth = 330;
            PreviewFrame.SetSize = new Vector2(180, 230);
            EquipmentScroll.HScrollEnabled = true;
        }

        SetupRoleName(loadout, proto);

        RoleSearch.PlaceHolder = Loc.GetString(antag != null && embedded
            ? "hologram-loadout-search-antag"
            : "hologram-loadout-search-job");
        RoleSearch.Text = RoleFilter;
        RoleSearch.OnTextChanged += args =>
        {
            RoleFilter = args.Text;
            RebuildRoles();
        };
        RoleSearchClear.ToolTip = Loc.GetString("hologram-loadout-search-clear");
        RoleSearchClear.OnPressed += _ =>
        {
            RoleSearch.Text = string.Empty;
            RoleFilter = string.Empty;
            RebuildRoles();
        };

        _slotMap = LoadoutSlotMap.Build(proto, _protoManager);
        foreach (var group in _slotMap.Groups)
        {
            var container = new LoadoutGroupContainer(profile, loadout, group, session, collection);
            var groupId = new ProtoId<LoadoutGroupPrototype>(group.ID);
            container.OnLoadoutPressed += args => OnLoadoutPressed?.Invoke(groupId, args);
            container.OnLoadoutUnpressed += args => OnLoadoutUnpressed?.Invoke(groupId, args);
            _groupContainers[group.ID] = container;
        }

        _cfg.OnValueChanged(CCCCVars.InterfaceStyle, OnInterfaceStyleChanged);

        RebuildRoles();
        RebuildEquipment();
    }

