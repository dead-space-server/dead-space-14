    /// <summary>
    /// Lets the header edit the shown job's priority (the jobs tab). <paramref name="lockReason"/> tells why the job
    /// can't be chosen, as the stock job list asks it.
    /// </summary>
    public void EnablePriorityEditing(Func<JobPrototype, FormattedMessage?> lockReason)
    {
        _priorityLock = lockReason;
        BuildPriorityRow();
    }

    /// <summary>
    /// Lets the header toggle the shown antagonist's preference (the antagonists tab). <paramref name="lockReason"/>
    /// tells why it can't be wanted, as the stock antagonist list asks it.
    /// </summary>
    public void EnableAntagPreference(Func<AntagPrototype, FormattedMessage?> lockReason)
    {
        _preferenceLock = lockReason;
        BuildPriorityRow();
    }

    /// <summary>Follows priority changes made by the editor: list markers and the header row.</summary>
    public void UpdatePriorities(HumanoidCharacterProfile profile)
    {
        Profile = profile;
        RebuildRoles();
        BuildPriorityRow();
    }

    private void BuildPriorityRow()
    {
        PriorityRow.RemoveAllChildren();

        if (AntagScreen)
        {
            BuildPreferenceToggle();
            return;
        }

        if (!_embedded || _job == null || _priorityLock == null)
        {
            PriorityRow.Visible = false;
            return;
        }

        PriorityRow.Visible = true;
        var job = _job;
        var current = Profile.JobPriorities.GetValueOrDefault(new ProtoId<JobPrototype>(job.ID), JobPriority.Never);
        var lockReason = _priorityLock(job);

        PriorityRow.AddChild(new Label
        {
            Text = Loc.GetString("hologram-loadout-priority"),
            VerticalAlignment = VAlignment.Center,
            StyleClasses = { StyleClass.LabelSubText },
        });

        foreach (var priority in new[] { JobPriority.Never, JobPriority.Low, JobPriority.Medium, JobPriority.High })
        {
            var button = new Button
            {
                Text = Loc.GetString($"humanoid-profile-editor-job-priority-{priority.ToString().ToLowerInvariant()}-button"),
                Pressed = priority == current,
                // A locked job can only stay at "never", as in the stock list.
                Disabled = lockReason != null && priority != JobPriority.Never,
                MinWidth = 64,
            };

            if (lockReason != null)
                button.ToolTip = lockReason.ToString();

            if (priority != current)
                button.OnPressed += _ => Defer(() => OnPriorityChanged?.Invoke(job, priority));

            PriorityRow.AddChild(button);
        }
    }

    private void BuildPreferenceToggle()
    {
        if (_antag == null || _preferenceLock == null)
        {
            PriorityRow.Visible = false;
            return;
        }

        PriorityRow.Visible = true;
        var antag = _antag;
        var wanted = Profile.AntagPreferences.Contains(antag.ID);
        var lockReason = _preferenceLock(antag);

        var toggle = new Button
        {
            Text = Loc.GetString(wanted ? "hologram-loadout-antag-wanted" : "hologram-loadout-antag-not-wanted"),
            ToggleMode = true,
            Pressed = wanted && lockReason == null,
            Disabled = lockReason != null,
            MinWidth = 140,
        };

        if (lockReason != null)
            toggle.ToolTip = lockReason.ToString();

        toggle.OnToggled += args => Defer(() => OnAntagPreferenceChanged?.Invoke(antag, args.Pressed));
        PriorityRow.AddChild(toggle);
    }

