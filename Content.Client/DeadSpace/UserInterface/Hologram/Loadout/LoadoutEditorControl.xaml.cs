    #region Equipment

    private void RaiseRole(object role)
    {
        switch (role)
        {
            case JobPrototype job:
                OnJobSelected?.Invoke(job);
                break;
            case AntagPrototype antag:
                OnAntagSelected?.Invoke(antag);
                break;
        }
    }

    private void RebuildEquipment()
    {
        UpdateHeader();
        ReloadDummy();
        BuildSlots();
        BuildGroupPanel();
    }

    /// <summary>
    /// Spawns the preview doll the way the server equips a spawning character: the role loadout first (in the order of
    /// the role's groups), then the job's starting gear into the slots that are still free.
    /// </summary>
    private void ReloadDummy()
    {
        DeleteEntities();

        var profile = Profile.WithLoadout(_loadout);
        EntityUid dummy;

        if (_antag != null)
        {
            // Same preview as the profile editor shows for antagonist loadouts.
            if (_antag.PreviewStartingGear is { } gear)
            {
                dummy = _lobby.LoadProfileEntity(profile, null, false);
                _lobby.GiveDummyAntagStartingGear(dummy, gear);
            }
            else
            {
                dummy = _lobby.LoadProfileEntity(profile, null, true);
            }

            _lobby.GiveDummyLoadout(dummy, _loadout);
        }
        else if (_job != null && (_job.JobPreviewEntity != null || _job.JobEntity != null))
        {
            // Borgs, AI and similar roles spawn a special entity without humanoid gear.
            dummy = _lobby.LoadProfileEntity(profile, _job, true);
        }
        else
        {
            dummy = _lobby.LoadProfileEntity(profile, null, false);
            _spawning.EquipRoleLoadout(dummy, _loadout, _roleProto);

            if (_job?.StartingGear != null)
                _spawning.EquipStartingGear(dummy, _job.StartingGear);
        }

        _dummy = dummy;
        _entManager.System<MetaDataSystem>().SetEntityName(dummy, Profile.Name);
        PreviewSprite.SetEntity(dummy);
        PreviewSprite.OverrideDirection = PreviewDirections[_direction];
    }

    private void RotatePreview(int step)
    {
        _direction = (_direction + step + PreviewDirections.Length) % PreviewDirections.Length;
        PreviewSprite.OverrideDirection = PreviewDirections[_direction];
    }

    private void BuildSlots()
    {
        LeftSlots.RemoveAllChildren();
        RightSlots.RemoveAllChildren();
        BottomSlots.RemoveAllChildren();
        _slotButtons.Clear();
        _shownSlots.Clear();

        if (_storagePreview != null)
        {
            _entManager.DeleteEntity(_storagePreview.Value);
            _storagePreview = null;
        }

        var primary = new List<SlotEntry>();
        var secondary = new List<SlotEntry>();

        if (_dummy is { } dummy && _inventory.TryGetSlots(dummy, out var definitions))
        {
            // The stripping layout orders slots from head to feet.
            foreach (var definition in definitions
                         .OrderBy(d => d.StrippingWindowPos.Y)
                         .ThenBy(d => d.StrippingWindowPos.X))
            {
                _inventory.TryGetSlotEntity(dummy, definition.Name, out var item);
                var groups = _slotMap.GetGroups(definition.Name);

                // An empty slot that nothing can fill is noise.
                if (item == null && groups.Count == 0)
                    continue;

                var entry = new SlotEntry(definition.Name, SlotCaption(definition.Name, definition.DisplayName), item, groups);

                // Slots hidden from the stripping menu (pockets, underwear) are secondary and go to the bottom row.
                if (definition.StripHidden)
                    secondary.Add(entry);
                else
                    primary.Add(entry);
            }

            var storageGroups = _slotMap.GetGroups(LoadoutSlotMap.StorageSlot);
            if (storageGroups.Count > 0)
            {
                primary.Add(new SlotEntry(
                    LoadoutSlotMap.StorageSlot,
                    SlotCaption(LoadoutSlotMap.StorageSlot, Loc.GetString("hologram-loadout-inventory")),
                    SpawnStoragePreview(storageGroups),
                    storageGroups));
            }
        }

        var leftCount = Math.Min(SlotsPerColumn, (primary.Count + 1) / 2);
        var rightCount = Math.Min(SlotsPerColumn, primary.Count - leftCount);
        var bottom = primary.Skip(leftCount + rightCount).Concat(secondary).ToList();

        foreach (var entry in primary.Concat(secondary))
        {
            _shownSlots.Add(entry.Slot);
        }

        if (_selectedSlot == null || !primary.Concat(secondary).Any(e => e.Slot == _selectedSlot && e.Groups.Count > 0))
        {
            _selectedSlot = primary.Take(leftCount + rightCount).Concat(bottom)
                .FirstOrDefault(e => e.Groups.Count > 0)?.Slot;
        }

        for (var i = 0; i < leftCount + rightCount; i++)
        {
            var column = i < leftCount ? LeftSlots : RightSlots;
            column.AddChild(CreateSlotButton(primary[i]));
        }

        foreach (var entry in bottom)
        {
            BottomSlots.AddChild(CreateSlotButton(entry));
        }

        BottomSlots.Visible = bottom.Count > 0;
        BottomDivider.Visible = bottom.Count > 0;
        NoSlotsLabel.Visible = primary.Count == 0 && secondary.Count == 0;
        NoSlotsLabel.Text = Loc.GetString("hologram-loadout-no-slots");
    }

    private LoadoutSlotButton CreateSlotButton(SlotEntry entry)
    {
        var configurable = entry.Groups.Count > 0;
        var button = new LoadoutSlotButton(entry.Slot, entry.Caption, entry.Item, configurable, _cog)
        {
            Selected = configurable && entry.Slot == _selectedSlot,
        };

        var itemName = entry.Item is { } item && _entManager.TryGetComponent(item, out MetaDataComponent? meta)
            ? meta.EntityName
            : Loc.GetString("hologram-loadout-slot-empty");
        var details = configurable
            ? Loc.GetString("hologram-loadout-slot-configurable",
                ("groups", string.Join(", ", entry.Groups.Select(g => Loc.GetString(g.Name)))))
            : Loc.GetString("hologram-loadout-slot-fixed");
        button.SetTooltip($"{itemName}\n{details}");

        if (configurable)
            button.OnSlotPressed += pressed => SelectSlot(pressed.Slot);

        _slotButtons.Add(button);
        return button;
    }

    private void SelectSlot(string slot)
    {
        _selectedSlot = slot;

        foreach (var button in _slotButtons)
        {
            button.Selected = button.Configurable && button.Slot == slot;
        }

        BuildGroupPanel();
    }

    /// <summary>The item shown on the inventory tile: the first selected loadout that adds something to storage.</summary>
    private EntityUid? SpawnStoragePreview(IReadOnlyList<LoadoutGroupPrototype> groups)
    {
        foreach (var group in groups)
        {
            if (!_loadout.SelectedLoadouts.TryGetValue(group.ID, out var selected))
                continue;

            foreach (var loadout in selected)
            {
                if (!_protoManager.Resolve(loadout.Prototype, out var loadoutProto))
                    continue;

                var proto = loadoutProto.DummyEntity ?? FirstStorageItem(loadoutProto);
                if (proto == null)
                    continue;

                _storagePreview = _entManager.SpawnEntity(proto, MapCoordinates.Nullspace);
                return _storagePreview;
            }
        }

        return null;
    }

    private EntProtoId? FirstStorageItem(LoadoutPrototype loadout)
    {
        if (_protoManager.Resolve(loadout.StartingGear, out var gear))
        {
            foreach (var items in gear.Storage.Values)
            {
                if (items is { Count: > 0 })
                    return items[0];
            }
        }

        foreach (var items in loadout.Storage.Values)
        {
            if (items is { Count: > 0 })
                return items[0];
        }

        return _loadoutSystem.GetFirstOrNull(loadout);
    }

    private string SlotCaption(string slot, string fallback)
    {
        return Caps(Loc.TryGetString($"hologram-loadout-slot-{slot.TrimStart('#')}", out var caption)
            ? caption
            : fallback);
    }

    private void DeleteEntities()
    {
        PreviewSprite.SetEntity(null);

        if (_dummy != null)
            _entManager.DeleteEntity(_dummy.Value);

        if (_storagePreview != null)
            _entManager.DeleteEntity(_storagePreview.Value);

        _dummy = null;
        _storagePreview = null;
    }

