    private void SetupRoleName(RoleLoadout loadout, RoleLoadoutPrototype proto)
    {
        if (!proto.CanCustomizeName)
        {
            RoleNameBox.Visible = false;
            return;
        }

        var maxLength = _cfg.GetCVar(CCVars.MaxLoadoutNameLength);
        var explanation = proto.NameDataset == null
            ? Loc.GetString("loadout-name-edit-label")
            : Loc.GetString("loadout-name-edit-label-dataset");

        LoadoutNameLabel.Text = Loc.GetString("hologram-loadout-name-label");
        RoleNameEdit.IsValid = text => text.Length <= maxLength;
        RoleNameEdit.PlaceHolder = explanation;
        RoleNameEdit.ToolTip = explanation + "\n" + Loc.GetString("loadout-name-edit-tooltip", ("max", maxLength));
        RoleNameEdit.Text = loadout.EntityName ?? string.Empty;
        RoleNameEdit.OnTextChanged += args => OnNameChanged?.Invoke(args.Text);
    }

    private void UpdateHeader()
    {
        HeaderTitle.Text = Caps(Loc.GetString(AntagScreen ? "hologram-loadout-antag-title" : "hologram-loadout-title"));

        // What the antagonist has to do, as the stock list shows it in the tooltip.
        RoleDescription.Visible = AntagScreen;
        if (_antag != null && AntagScreen)
            RoleDescription.Text = Loc.GetString(_antag.Objective);

        var roleName = _antag != null
            ? Loc.GetString(_antag.Name)
            : _job?.LocalizedName ?? string.Empty;
        HeaderRole.Text = roleName.Length == 0
            ? string.Empty
            : Loc.GetString("hologram-loadout-header-role", ("role", Caps(roleName)));

        // Only roles that budget their loadout in points have a balance to show.
        if (_roleProto.Points is not { } maxPoints)
        {
            PointsLabel.Visible = false;
            return;
        }

        PointsLabel.Visible = true;
        PointsLabel.Text = Loc.GetString("hologram-loadout-points",
            ("count", _loadout.Points ?? RemainingPoints(maxPoints)),
            ("max", maxPoints));
    }

    /// <summary>Points left after the direct costs of the selected loadouts, for a loadout that wasn't validated yet.</summary>
    private int RemainingPoints(int maxPoints)
    {
        var points = maxPoints;

        foreach (var selected in _loadout.SelectedLoadouts.Values)
        {
            foreach (var loadout in selected)
            {
                if (!_protoManager.Resolve(loadout.Prototype, out var loadoutProto))
                    continue;

                foreach (var effect in loadoutProto.Effects)
                {
                    if (effect is PointsCostLoadoutEffect cost)
                        points -= cost.Cost;
                }
            }
        }

        return points;
    }

