namespace Content.Client.DeadSpace.UserInterface.Hologram.Appearance;

/// <summary>
/// The appearance screen of the profile editor's appearance tab in the "Dead Space" style: the basic fields on the
/// left, the character in the centre between labelled slots (skin, eyes, hair and every marking category the species
/// offers) and the picker of the selected slot on the right. The fields and pickers are the editor's own controls,
/// borrowed while the screen exists and returned when it is disposed, so every change still goes through the editor's
/// existing handlers, validation and saving.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class AppearanceEditorControl : BoxContainer
{
    private const string CogTexture = "/Textures/Interface/VerbIcons/settings.svg.192dpi.png";
    private const string SkinSlot = "#skin";
    private const string EyesSlot = "#eyes";
    private const int SlotsPerColumn = 7;

    private static readonly Direction[] PreviewDirections =
        [Direction.South, Direction.East, Direction.North, Direction.West];

    private readonly IPrototypeManager _protoManager;
    private readonly SpriteSystem _sprite;
    private readonly MarkingManager _markingManager;
    private readonly MarkingPicker _markingPicker;
    private readonly Texture _cog;

    /// <summary>The editor's controls for the slots that aren't marking categories, by slot.</summary>
    private readonly Dictionary<string, Control> _hosted = new();

    /// <summary>Borrowed controls with their original place, in borrowing order.</summary>
    private readonly List<(Control Control, Control? Parent, int Index)> _borrowed = new();

    private readonly List<LoadoutSlotButton> _slotButtons = new();
    private readonly List<string> _slots = new();

    private string? _selectedSlot;
    private string? _shownSlot;
    private int _direction;

    public AppearanceEditorControl(
        IDependencyCollection collection,
        MarkingManager markingManager,
        Control basic,
        Control skin,
        Control eyes,
        Control hair,
        Control facialHair,
        MarkingPicker markingPicker)
    {
        RobustXamlLoader.Load(this);

        _protoManager = collection.Resolve<IPrototypeManager>();
        _sprite = collection.Resolve<IEntityManager>().System<SpriteSystem>();
        _cog = collection.Resolve<IResourceCache>().GetTexture(CogTexture);
        _markingManager = markingManager;
        _markingPicker = markingPicker;

        BasicPanel.PanelOverride = new LoadoutStyleBox(LoadoutBoxKind.Panel, 8);
        DollPanel.PanelOverride = new LoadoutStyleBox(LoadoutBoxKind.Panel, 8);
        OptionsPanel.PanelOverride = new LoadoutStyleBox(LoadoutBoxKind.Panel, 8);

        PreviewSprite.WorldRotation = Angle.Zero;
        RotateLeftButton.OnPressed += _ => RotatePreview(1);
        RotateRightButton.OnPressed += _ => RotatePreview(-1);

        Borrow(basic);
        Borrow(skin);
        Borrow(eyes);
        Borrow(hair);
        Borrow(facialHair);
        Borrow(markingPicker);
        markingPicker.CategorySelectorVisible = false;
        markingPicker.StackLists = true;

        BasicHost.AddChild(basic);
        _hosted[SkinSlot] = skin;
        _hosted[EyesSlot] = eyes;
        _hosted[nameof(MarkingCategories.Hair)] = hair;
        _hosted[nameof(MarkingCategories.FacialHair)] = facialHair;
    }

    /// <summary>
    /// Follows the edited profile: the doll, the slot previews and the set of slots (species and sex change which
    /// marking categories exist).
    /// </summary>
    public void Refresh(HumanoidCharacterProfile? profile, EntityUid preview)
    {
        if (profile == null || _borrowed.Count == 0)
            return;

        PreviewSprite.SetEntity(preview);
        PreviewSprite.OverrideDirection = PreviewDirections[_direction];

        BuildSlots(profile);

        if (_selectedSlot == null || !_slots.Contains(_selectedSlot))
            _selectedSlot = _slots.Count > 0 ? _slots[0] : null;

        // Re-showing the same picker would reset its lists and selection on every change made in it.
        if (_selectedSlot != _shownSlot)
            ShowSelected();
        else
            UpdateSelection();
    }

    protected override void Dispose(bool disposing)
    {
        // The borrowed controls belong to the profile editor: give them back before this control disposes its tree.
        if (disposing)
            ReturnBorrowed();

        base.Dispose(disposing);
    }

    #region Borrowing

    private void Borrow(Control control)
    {
        var parent = control.Parent;
        var index = parent == null ? 0 : control.GetPositionInParent();
        control.Orphan();
        _borrowed.Add((control, parent, index));
    }

    private void ReturnBorrowed()
    {
        // Reverse order puts siblings back at their original indices.
        for (var i = _borrowed.Count - 1; i >= 0; i--)
        {
            var (control, parent, index) = _borrowed[i];
            control.Orphan();

            if (parent == null || parent.Disposed)
                continue;

            parent.AddChild(control);
            control.SetPositionInParent(Math.Min(index, parent.ChildCount - 1));
        }

        _borrowed.Clear();
        _markingPicker.CategorySelectorVisible = true;
        _markingPicker.StackLists = false;
        _shownSlot = null;
    }

    #endregion

    #region Slots

    private void BuildSlots(HumanoidCharacterProfile profile)
    {
        LeftSlots.RemoveAllChildren();
        RightSlots.RemoveAllChildren();
        BottomSlots.RemoveAllChildren();
        _slotButtons.Clear();
        _slots.Clear();

        var appearance = profile.Appearance;
        var eyes = (EyesSlot, Loc.GetString("hologram-appearance-slot-eyes"), Swatch(appearance.EyeColor), string.Empty);
        var entries = new List<(string Slot, string Caption, Control Content, string Tooltip)>
        {
            (SkinSlot, Loc.GetString("hologram-appearance-slot-skin"), Swatch(appearance.SkinColor), string.Empty),
        };

        _protoManager.TryIndex(profile.Species, out SpeciesPrototype? species);
        MarkingPointsPrototype? points = null;
        if (species != null)
            _protoManager.TryIndex(species.MarkingPoints, out points);

        var used = new MarkingSet(appearance.Markings, _markingManager);

        foreach (var category in Enum.GetValues<MarkingCategories>())
        {
            // Every category the species can actually pick from becomes a slot.
            if (species == null ||
                _markingManager.MarkingsByCategoryAndSpeciesAndSex(category, species.ID, profile.Sex).Count == 0)
            {
                continue;
            }

            var slot = category.ToString();
            var caption = Loc.GetString($"markings-category-{slot}");
            entries.Add((slot, caption, CategoryPreview(category, profile), PointsTooltip(category, points, used)));

            // Eyes sit with the face, right after facial hair.
            if (category == MarkingCategories.FacialHair)
                entries.Add(eyes);
        }

        if (!entries.Exists(e => e.Slot == EyesSlot))
            entries.Insert(1, eyes);

        var leftCount = Math.Min(SlotsPerColumn, (entries.Count + 1) / 2);
        var rightCount = Math.Min(SlotsPerColumn, entries.Count - leftCount);

        for (var i = 0; i < entries.Count; i++)
        {
            var (slot, caption, content, tooltip) = entries[i];
            _slots.Add(slot);

            var button = new LoadoutSlotButton(slot, Caps(caption), content, true, _cog);
            button.SetTooltip(tooltip.Length == 0 ? caption : $"{caption}\n{tooltip}");
            button.OnSlotPressed += pressed => SelectSlot(pressed.Slot);
            _slotButtons.Add(button);

            if (i < leftCount)
                LeftSlots.AddChild(button);
            else if (i < leftCount + rightCount)
                RightSlots.AddChild(button);
            else
                BottomSlots.AddChild(button);
        }

        var bottom = entries.Count > leftCount + rightCount;
        BottomSlots.Visible = bottom;
        BottomDivider.Visible = bottom;
    }

    /// <summary>The current marking of a category drawn in its colour, or nothing when the category is empty.</summary>
    private Control CategoryPreview(MarkingCategories category, HumanoidCharacterProfile profile)
    {
        var appearance = profile.Appearance;
        string? markingId = null;
        var color = Color.White;

        switch (category)
        {
            case MarkingCategories.Hair:
                markingId = appearance.HairStyleId;
                color = appearance.HairColor;
                break;
            case MarkingCategories.FacialHair:
                markingId = appearance.FacialHairStyleId;
                color = appearance.FacialHairColor;
                break;
            default:
                foreach (var marking in appearance.Markings)
                {
                    if (!_markingManager.TryGetMarking(marking, out var proto) || proto.MarkingCategory != category)
                        continue;

                    markingId = marking.MarkingId;
                    if (marking.MarkingColors.Count > 0)
                        color = marking.MarkingColors[0];
                    break;
                }

                break;
        }

        if (markingId == null ||
            !_markingManager.Markings.TryGetValue(markingId, out var markingProto) ||
            markingProto.Sprites.Count == 0)
        {
            return new Control();
        }

        return new TextureRect
        {
            Texture = _sprite.Frame0(markingProto.Sprites[0]),
            Stretch = TextureRect.StretchMode.KeepCentered,
            ModulateSelfOverride = color,
        };
    }

    private static string PointsTooltip(MarkingCategories category, MarkingPointsPrototype? points, MarkingSet used)
    {
        if (points == null || !points.Points.TryGetValue(category, out var limit))
            return string.Empty;

        var taken = used.Markings.TryGetValue(category, out var list) ? list.Count : 0;
        var text = Loc.GetString("hologram-appearance-points", ("count", taken), ("max", limit.Points));
        return limit.Required ? $"{text}\n{Loc.GetString("hologram-appearance-required")}" : text;
    }

    private static Control Swatch(Color color)
    {
        return new PanelContainer
        {
            Margin = new Thickness(8),
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = color,
                BorderColor = Color.Black.WithAlpha(0.6f),
                BorderThickness = new Thickness(1),
            },
        };
    }

    private void SelectSlot(string slot)
    {
        _selectedSlot = slot;
        ShowSelected();
    }

    private void UpdateSelection()
    {
        foreach (var button in _slotButtons)
        {
            button.Selected = button.Slot == _selectedSlot;
        }
    }

    private void ShowSelected()
    {
        UpdateSelection();
        OptionsHost.RemoveAllChildren();
        _shownSlot = _selectedSlot;

        var caption = Loc.GetString("hologram-appearance-title");
        if (_selectedSlot == null)
        {
            OptionsTitle.Text = Caps(caption);
            return;
        }

        Control control;
        if (_hosted.TryGetValue(_selectedSlot, out var hosted))
        {
            control = hosted;
        }
        else if (Enum.TryParse<MarkingCategories>(_selectedSlot, out var category) &&
                 _markingPicker.SelectCategory(category))
        {
            control = _markingPicker;
        }
        else
        {
            OptionsTitle.Text = Caps(caption);
            return;
        }

        var slotCaption = _selectedSlot switch
        {
            SkinSlot => Loc.GetString("hologram-appearance-slot-skin"),
            EyesSlot => Loc.GetString("hologram-appearance-slot-eyes"),
            _ => Loc.GetString($"markings-category-{_selectedSlot}"),
        };

        OptionsTitle.Text = Caps(Loc.GetString("hologram-loadout-inventory-slot", ("inventory", caption), ("slot", slotCaption)));
        control.Orphan();
        OptionsHost.AddChild(control);
    }

    #endregion

    private void RotatePreview(int step)
    {
        _direction = (_direction + step + PreviewDirections.Length) % PreviewDirections.Length;
        PreviewSprite.OverrideDirection = PreviewDirections[_direction];
    }

    private static string Caps(string text)
    {
        return DeadSpaceStylePalette.Hologram ? text.ToUpper(CultureInfo.CurrentCulture) : text;
    }
}
