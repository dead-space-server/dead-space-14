using Content.Shared.DeadSpace.Autopsy;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Client.UserInterface.Controls;
using Robust.Shared.Timing;

namespace Content.Client.DeadSpace.Autopsy.AutopsyScanner.UI;

[GenerateTypedNameReferences]
public sealed partial class AutopsyScannerWindow : DefaultWindow
{
    private readonly IGameTiming _gameTiming;

    private const int AnalyzerHeight = 515;
    private const int AnalyzerWidth = 340;

    public AutopsyScannerWindow()
    {
        RobustXamlLoader.Load(this);

        _gameTiming = IoCManager.Instance!.Resolve<IGameTiming>();
    }

    public void Populate(AutopsyScannerScannedUserMessage msg)
    {
        OrgansContainer.RemoveAllChildren();
        NoPatientDataText.Visible = false;

        PatientName.Text = msg.EntityName ?? Loc.GetString("autopsy-scanner-window-entity-unknown-text");

        IdentityText.Visible = !string.IsNullOrEmpty(msg.IdentityText);

        if (IdentityText.Visible)
        {
            IdentityText.Text = Loc.GetString(
                "autopsy-scanner-window-identity-text",
                ("identity", msg.IdentityText!)
            );
        }

        if (msg.Details.Count == 0)
        {
            OrgansContainer.AddChild(CreateLabel(Loc.GetString("autopsy-scanner-window-organ-clean")));
        }
        else
        {
            foreach (var detail in msg.Details)
            {
                OrgansContainer.AddChild(CreateLabel(Loc.GetString(
                    "autopsy-scanner-window-organ-detail",
                    ("type", detail.Type),
                    ("amount", detail.Amount),
                    ("source", detail.Source),
                    ("time", $"{_gameTiming.CurTime - detail.Time:m\\:ss}")
                )));
            }
        }

        if (msg.Traces.Count > 0)
        {
            OrgansContainer.AddChild(CreateLabel(Loc.GetString(
                "autopsy-scanner-window-organ-traces",
                ("traces", string.Join(", ", msg.Traces))
            )));
        }

        SetHeight = AnalyzerHeight;
        SetWidth = AnalyzerWidth;
    }

    private static Label CreateLabel(string text)
    {
        return new Label
        {
            Margin = new Thickness(2, 2),
            Text = text,
        };
    }
}
