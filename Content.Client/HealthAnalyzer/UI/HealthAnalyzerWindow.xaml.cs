    public HealthAnalyzerWindow()
    {
        RobustXamlLoader.Load(this);

        // DS14-start
        var sprites = IoCManager.Resolve<IEntitySystemManager>().GetEntitySystem<SpriteSystem>();
        WindowPrintButton.Visible = true;
        WindowPrintButton.TextureNormal = sprites.Frame0(new SpriteSpecifier.Rsi(
            new ResPath("/Textures/Objects/Misc/module.rsi"),
