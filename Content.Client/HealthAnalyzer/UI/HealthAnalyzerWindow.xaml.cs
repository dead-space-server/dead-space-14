        WindowPrintButton.Scale = new Vector2(0.85f, 0.85f);
        WindowPrintButton.ToolTip = Loc.GetString("health-analyzer-print");
        WindowPrintButton.OnPressed += _ => OnPrintButtonPressed?.Invoke();
        // DS14-end
    }

    public void Populate(HealthAnalyzerUiState state)
    {
        HealthAnalyzer.Populate(state);
    }
}