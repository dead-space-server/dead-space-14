    private void WriteLimbText(BoxContainer text)
    {
        var marks = new SortedDictionary<int, bool>();
        var words = new Dictionary<int, List<string>>();
        LimbBodyComponent? limbBody = null; //DS-14
        SurgeryCavityComponent? hold = null; //DS-14
        SurgeryInfectionComponent? infection = null; //DS-14
        if (_limbPatient is { } net && _entityManager.TryGetEntity(net, out var scanned)) //DS-14
        {
            _entityManager.TryGetComponent(scanned.Value, out limbBody); //DS-14
            _entityManager.TryGetComponent(scanned.Value, out hold); //DS-14
            _entityManager.TryGetComponent(scanned.Value, out infection); //DS-14
        }

        void Mark(int index, bool urgent)
        {
            if ((uint) index >= (uint) LimbWoundRules.BodyZoneCount)
                return;

            if (marks.TryGetValue(index, out var already))
                marks[index] = already || urgent;
            else
                marks[index] = urgent;
        }

        void Note(int index, string word) //DS-14
        {
            if (!words.TryGetValue(index, out var list))
            {
                list = new List<string>();
                words[index] = list;
            }

            if (!list.Contains(word))
                list.Add(word);
        }

        if (_limbIssueCache != null)
        {
            foreach (var issue in _limbIssueCache)
            {
                if (issue.Kind == LimbIssueKind.Scar && !_limbDetailed)
                    continue;

                int index;
                if (issue.Organ)
                {
                    if (!Enum.IsDefined(typeof(LimbOrgan), issue.Index))
                        continue;

                    var home = LimbOrganHomes.Home((LimbOrgan) issue.Index);
                    if (!LimbWoundRules.IsBody(home))
                        continue;

                    index = LimbWoundRules.Index(home);
                }
                else
                {
                    index = issue.Index;
                }

                var urgent = issue.Kind is LimbIssueKind.Severed
                    or LimbIssueKind.Rupture
                    or LimbIssueKind.Atrophy
                    or LimbIssueKind.OpenFracture
                    or LimbIssueKind.RibOpen
                    or LimbIssueKind.BurnThird
                    or LimbIssueKind.Embedded;
                Mark(index, urgent);

                var prefix = _limbMachine ? "health-analyzer-issue-machine-" : "health-analyzer-issue-";
                var word = Loc.GetString($"{prefix}{(byte) issue.Kind}");
                if (!_limbMachine && issue.Kind == LimbIssueKind.Bleed && limbBody != null && (uint) index < (uint) limbBody.Zones.Count) //DS-14
                    word = Loc.GetString("surgery-xray-bleed", ("level", SurgeryXrayReport.BleedLevel(limbBody.Zones[index].Bleed)));
                if (issue.Organ)
                    word = $"{word} ({Loc.GetString($"health-analyzer-organ-{issue.Index}")})";

                Note(index, word);
            }
        }

        //DS-14 start
        for (var i = 0; i < LimbWoundRules.BodyZoneCount; i++)
        {
            var hidden = new List<string>();
            SurgeryXrayReport.NoteHidden((LimbZone) i, hold, infection, hidden);
            if (hidden.Count == 0)
                continue;

            Mark(i, infection != null && infection.Rots((LimbZone) i));
            foreach (var line in hidden)
                Note(i, line);
        }
        //DS-14 end

        if (_limbShadeCache != null)
        {
            var count = Math.Min(_limbShadeCache.Count, LimbWoundRules.BodyZoneCount);
            for (var i = 0; i < count; i++)
            {
                var shade = _limbShadeCache[i];
                if (shade == LimbScan.Fine)
                    continue;

                Mark(i, shade is LimbScan.Critical or LimbScan.Missing);
            }
        }

        foreach (var (index, urgent) in marks)
        {
            var name = Loc.GetString($"health-analyzer-zone-{index}");
            var phrase = words.TryGetValue(index, out var found) && found.Count > 0
                ? string.Join(", ", found)
                : Loc.GetString("health-analyzer-limb-hurt");
            text.AddChild(new Label
            {
                Text = $"{name}: {phrase}",
                FontColorOverride = urgent ? Color.FromHex("#c43838") : Color.FromHex("#d6c14a"),
            });
        }
    }

    private byte[] SyncShades(IReadOnlyList<byte>? shades, NetEntity? patient)
    {
        var next = shades == null ? Array.Empty<byte>() : shades.ToArray();
        if (patient == null
            || !_entityManager.TryGetEntity(patient.Value, out var body)
            || !_entityManager.TryGetComponent<LimbBodyComponent>(body.Value, out var limbs))
            return next;

        var count = Math.Min(limbs.Zones.Count, LimbWoundRules.BodyZoneCount);
        if (next.Length < count)
            Array.Resize(ref next, count);

        for (var i = 0; i < count; i++)
        {
            var state = limbs.Zones[i];
            if (state.Severed)
            {
                next[i] = LimbScan.Missing;
                continue;
            }

            var pool = LimbWoundRules.HealthFor((LimbZone) i, limbs);
            var hp = pool <= 0f ? 0f : Math.Clamp(state.Health / pool, 0f, 1f);
            var shown = pool <= 0f ? 0f : Math.Clamp((pool - ZoneDamage(limbs, i)) / pool, 0f, 1f);
            var left = Math.Min(hp, shown);
            next[i] = state.Atrophied || state.Health <= 0f || left <= 0.02f
                ? LimbScan.Missing
                : left <= 0.34f
                    ? LimbScan.Critical
                    : left <= 0.67f
                        ? LimbScan.Bad
                        : left < 0.98f
                            ? LimbScan.Hurt
                            : LimbScan.Fine;
        }

        return next;
    }

    private float ZoneDamage(LimbBodyComponent limbs, int index)
    {
        if (_generalTypes == null || (uint) index >= (uint) limbs.Zones.Count)
            return 0f;

        var wounds = _entityManager.System<LimbWoundSystem>();
        var total = 0f;
        foreach (var (type, amount) in _generalTypes)
        {
            if (amount <= FixedPoint2.Zero)
                continue;

            var all = 0f;
            var zones = Math.Min(limbs.Zones.Count, LimbWoundRules.BodyZoneCount);
            for (var i = 0; i < zones; i++)
                all += wounds.LedgerFor(limbs.Zones[i], type);

            var share = all > 0f
                ? wounds.LedgerFor(limbs.Zones[index], type) / all
                : index == (int) LimbZone.Torso ? 1f : 0f;
            total += (float) amount * share;
        }

        return total;
    }

    private void ShowDamage()
    {
        if (ShowZoneDamage())
            return;

        DamageTitleLabel.Text = Loc.GetString("health-analyzer-window-entity-damage-total-text");
        DamageLabel.Text = _generalTotal.ToString();
        NoteDamage(_generalTotal, null);
        if (_generalGroups != null && _generalTypes != null)
            DrawDiagnosticGroups(_generalGroups, _generalTypes);
    }

    /// <summary>
    /// The picked part's share of each damage type, split by the per-zone hit ledger, so the parts add up to the total.
    /// </summary>
    private bool ShowZoneDamage()
    {
        if (_limbPick is not { } pick
            || _generalTypes == null
            || _limbPatient is not { } net
            || !_entityManager.TryGetEntity(net, out var body)
            || !_entityManager.TryGetComponent<LimbBodyComponent>(body.Value, out var limbs))
            return false;

        if (LimbWoundRules.IsSmall(pick))
            pick = LimbZone.Head;

        var index = LimbWoundRules.Index(pick);
        if (!LimbWoundRules.IsBody(pick) || (uint) index >= (uint) limbs.Zones.Count)
            return false;

        var wounds = _entityManager.System<LimbWoundSystem>();
        var types = new Dictionary<string, FixedPoint2>();
        var total = FixedPoint2.Zero;
        foreach (var (type, amount) in _generalTypes)
        {
            if (amount <= FixedPoint2.Zero)
                continue;

            var all = 0f;
            for (var i = 0; i < limbs.Zones.Count && i < LimbWoundRules.BodyZoneCount; i++)
                all += wounds.LedgerFor(limbs.Zones[i], type);

            var share = all > 0f
                ? wounds.LedgerFor(limbs.Zones[index], type) / all
                : pick == LimbZone.Torso ? 1f : 0f;
            var part = amount * share;
            if (part <= FixedPoint2.Zero)
                continue;

            types[type] = part;
            total += part;
        }

        var groups = new Dictionary<string, FixedPoint2>();
        foreach (var group in _prototypes.EnumeratePrototypes<DamageGroupPrototype>())
        {
            var sum = FixedPoint2.Zero;
            foreach (var type in group.DamageTypes)
            {
                if (types.TryGetValue(type, out var value))
                    sum += value;
            }

            if (sum > FixedPoint2.Zero)
                groups[group.ID] = sum;
        }

        DamageTitleLabel.Text = Loc.GetString("limb-analyzer-zone-damage");
        DamageLabel.Text = total.ToString();
        NoteDamage(total, pick);
        DrawDiagnosticGroups(groups.OrderByDescending(g => g.Value).ToDictionary(g => g.Key, g => g.Value), types);
        return true;
    }
