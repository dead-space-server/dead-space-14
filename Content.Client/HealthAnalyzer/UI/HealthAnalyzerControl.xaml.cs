    private void DrawInjectedReagents(IReadOnlyList<HealthAnalyzerReagentEntry>? reagents)
    {
        ReagentsContainer.RemoveAllChildren();

        var showReagents = reagents != null && reagents.Count > 0;
        ReagentsDivider.Visible = showReagents;
        ReagentsContainer.Visible = showReagents;

        if (reagents == null || reagents.Count == 0)
            return;

        ReagentsContainer.AddChild(new Label
        {
            Text = Loc.GetString("health-analyzer-window-reagents-title"),
            FontColorOverride = Color.FromHex("#d7b56d"),
            Margin = new Thickness(0, 0, 0, 3),
        });

        foreach (var reagent in reagents)
        {
            var name = _prototypes.TryIndex<ReagentPrototype>(reagent.ReagentId, out var prototype)
                ? prototype.LocalizedName
                : reagent.ReagentId;

            var amount = $"{name}: {reagent.Quantity}{Loc.GetString("health-analyzer-window-reagents-unit")}";
            var escapedAmount = FormattedMessage.EscapeText(amount);
            var label = new RichTextLabel
            {
                HorizontalExpand = true,
                Margin = new Thickness(0, 1),
            };

            var harm = reagent.Overdosed || AlwaysHarms(reagent.ReagentId);
            label.SetMessage(harm
                ? FormattedMessage.FromMarkupPermissive($"[bold][color=red]{escapedAmount}[/color][/bold]")
                : FormattedMessage.FromUnformatted(amount));

            var row = new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal,
                HorizontalExpand = true,
            };
            row.AddChild(label);
            var tone = _prototypes.TryIndex<ReagentPrototype>(reagent.ReagentId, out var colored)
                ? colored.SubstanceColor
                : Color.FromHex("#8a8a9a");
            if (harm)
                tone = Color.FromHex("#c45c5c");
            row.AddChild(new PanelContainer
            {
                MinSize = new Vector2(4, 14),
                VerticalAlignment = VAlignment.Center,
                Margin = new Thickness(8, 0, 0, 0),
                PanelOverride = new StyleBoxFlat { BackgroundColor = tone },
            });

            ReagentsContainer.AddChild(row);
        }
    }

    private bool AlwaysHarms(string reagentId)
    {
        if (!_prototypes.TryIndex<ReagentPrototype>(reagentId, out var prototype) || prototype.Metabolisms == null)
            return false;

        foreach (var metabolism in prototype.Metabolisms.Values)
        {
            foreach (var effect in metabolism.Effects)
            {
                if (effect is not HealthChange change || change.Conditions is { Length: > 0 })
                    continue;

                foreach (var (_, amount) in change.Damage.DamageDict)
                {
                    if (amount > FixedPoint2.Zero)
                        return true;
                }
            }
        }

        return false;
    }

    private void NoteDamage(FixedPoint2 damage, LimbZone? zone)
    {
        var max = Pool(zone);
        var left = Math.Max(0f, max - (float) damage);
        var pct = max <= 0f ? 0f : left / max * 100f;
        if (zone is { } part
            && _limbPatient is { } net
            && _entityManager.TryGetEntity(net, out var owner)
            && _entityManager.TryGetComponent<LimbBodyComponent>(owner.Value, out var limbs))
        {
            var index = LimbWoundRules.Index(LimbWoundRules.IsSmall(part) ? LimbZone.Head : part);
            if ((uint) index < (uint) limbs.Zones.Count)
            {
                var state = limbs.Zones[index];
                var real = state.Severed || state.Atrophied ? 0f : Math.Clamp(state.Health / max, 0f, 1f) * 100f;
                pct = Math.Min(pct, real);
            }
        }

        HealthTitle.Text = Loc.GetString(zone == null ? "health-analyzer-meter-health" : "health-analyzer-meter-condition");
        HealthReadout.Text = $"{pct:0}%";
        HealthBar.MaxValue = 100f;
        HealthBar.Value = pct;
        var amount = (float) damage;
        DamageLabel.FontColorOverride = amount > 200f
            ? Color.FromHex("#c43838")
            : amount >= 100f
                ? Color.FromHex("#e07a2f")
                : amount > 50f
                    ? Color.FromHex("#d6c14a")
                    : Color.White;
    }

    private void ShowRot(EntityUid body)
    {
        var rot = 0f;
        if (_entityManager.TryGetComponent<PerishableComponent>(body, out var perish) && perish.RotAfter > TimeSpan.Zero)
            rot = (float) (perish.RotAccumulator.TotalSeconds / perish.RotAfter.TotalSeconds * 100d);

        if (_entityManager.HasComponent<RottingComponent>(body))
            rot = Math.Max(rot, 100f);

        if (_entityManager.TryGetComponent<SurgeryInfectionComponent>(body, out var infection) && infection.Rotting.Count > 0)
            rot = Math.Max(rot, infection.Rotting.Count / (float) LimbWoundRules.BodyZoneCount * 100f);

        RotPanel.Visible = rot > 0.5f;
        RotLabel.Text = $"{Math.Clamp(rot, 0f, 100f):0}%";
    }

    private float Pool(LimbZone? zone)
    {
        LimbBodyComponent? limbs = null;
        if (_limbPatient is { } net && _entityManager.TryGetEntity(net, out var body))
            _entityManager.TryGetComponent(body.Value, out limbs);

        if (zone is { } picked)
        {
            if (LimbWoundRules.IsSmall(picked))
                picked = LimbZone.Head;
            return Math.Max(1f, LimbWoundRules.HealthFor(picked, limbs));
        }

        var sum = 0f;
        for (var i = 0; i < LimbWoundRules.BodyZoneCount; i++)
            sum += LimbWoundRules.HealthFor((LimbZone) i, limbs);
        return Math.Max(1f, sum);
    }

    private static Color GroupColor(string id)
    {
        return id switch
        {
            "Brute" => Color.FromHex("#c45c5c"),
            "Burn" => Color.FromHex("#d08a3a"),
            "Airloss" => Color.FromHex("#5aa0c8"),
            "Toxin" => Color.FromHex("#6aaa4a"),
            "Genetic" => Color.FromHex("#9a6ad0"),
            "Metaphysical" => Color.FromHex("#c46ad0"),
            _ => Color.FromHex("#8a8a9a"),
        };
    }
